const (
	// winePackKey, winePackAsset and winePackRoot name the Box64 pack in
	// JukaHub's releases (relpack.go).
	winePackKey   = "wine"
	winePackAsset = "JukaHub-Wine-linux-arm64.zip"
	winePackTitle = "the Windows app runtime"
	winePackRoot  = "wine-runtime"
	// Box64 with its recompiler is tens of megabytes; the bounds leave room
	// for a few more x86-64 libraries without accepting anything absurd.
	winePackMaxAsset    = int64(200 << 20)
	winePackMaxUnpacked = int64(400 << 20)
	// wineSpecName is the pack's description of the Wine build to fetch.
	wineSpecName = "wine.json"
	// wineTreeMarkerName records, inside an unpacked Wine, which tarball it
	// came from.
	wineTreeMarkerName = ".jukahub-wine.json"
	// wineMaxTarball bounds the Wine download (Kron4ek's 10.0 build is about
	// 62 MB).
	wineMaxTarball = int64(400 << 20)
	// wineUnpackFactor estimates what a Wine .tar.xz unpacks to, for the
	// free-space check: stripped binaries and PE DLLs compress six to eight
	// times.
	wineUnpackFactor = int64(10)
	// wineWrapperTag marks the wrapper scripts this file writes.
	wineWrapperTag = "# JukaHub Wine wrapper v1"
	// hangoverWrapperMark is the line the Hangover installer's wrapper
	// carries (writeWineWrapper).
	hangoverWrapperMark = "# Generated by JukaHub's Windows runtime installer."
	// wineDownloadTries is how often one install starts the Wine download: a
	// download cut off after it made progress is resumed.
	wineDownloadTries = 3
)

// wineNativeSpec is the Wine an x86-64 Linux PC without a Wine of its own
// gets: the same Kron4ek release the ARM pack names. The SHA-256 is the one
// the release publishes (mirrors of it quote the same value); the size is not
// pinned, so only wineMaxTarball bounds it.
var wineNativeSpec = wineTarballSpec{
	Version: "10.0",
	Asset:   "wine-10.0-amd64-wow64.tar.xz",
	URL:     "https://github.com/Kron4ek/Wine-Builds/releases/download/10.0/wine-10.0-amd64-wow64.tar.xz",
	SHA256:  "aeebbbf239e548f0136f1cd72a2e109dd9a572a8f703da3c09fa40d74d5c255f",
}

// wineTarballSpec is one Wine build: the pack's wine.json, or wineNativeSpec.
type wineTarballSpec struct {
	Version string `json:"version"`
	Asset   string `json:"asset"`
	URL     string `json:"url"`
	SHA256  string `json:"sha256"`
	Size    int64  `json:"size,omitempty"`
}

// wineTreeMarker is what an unpacked Wine records about itself.
type wineTreeMarker struct {
	wineTarballSpec
	InstalledAt string `json:"installed_at"`
}

// winePackSupported reports whether this device runs Wine through the Box64
// pack: ARM64 Linux, the handheld's platform.
func winePackSupported() bool { return runtime.GOOS == "linux" && runtime.GOARCH == "arm64" }

// wineNativeSupported reports whether this device runs Kron4ek's x86-64 Wine
// directly.
func wineNativeSupported() bool { return runtime.GOOS == "linux" && runtime.GOARCH == "amd64" }

// windowsRuntimeInstallable reports whether JukaHub can install a Wine here.
func windowsRuntimeInstallable() bool { return winePackSupported() || wineNativeSupported() }

// winePackDir is where the Box64 pack is installed.
func winePackDir() string { return filepath.Join(windowsRuntimeDir(), "pack") }

// wineWrapperDir holds bin/wine, bin/wineserver and bin/box64: resolveWine
// looks for bin/wine there first.
func wineWrapperDir() string { return filepath.Join(windowsRuntimeDir(), "bin") }

// winePackSpecFor describes the Box64 pack for relPackInstall.
func winePackSpecFor() relPackSpec {
	return relPackSpec{
		Key:         winePackKey,
		Asset:       winePackAsset,
		Title:       winePackTitle,
		MaxAsset:    winePackMaxAsset,
		MaxUnpacked: winePackMaxUnpacked,
		Root:        winePackRoot,
		Probe:       winePackProbe,
		Supported:   winePackSupported,
	}
}

// winePackProbe says why the staged pack in dir would not run here: no box64,
// an unreadable wine.json, a box64 this firmware's loader refuses (elfcompat's
// wording), or one that does not answer --version.
func winePackProbe(dir string) string {
	box := filepath.Join(dir, "box64", "box64")
	if !regularFile(box) {
		return "the package has no box64/box64"
	}
	if _, err := readWineTarballSpec(dir); err != nil {
		return err.Error()
	}
	if problem := nativeLoadProblem(box); problem != "" {
		if strings.HasPrefix(problem, "needs ") {
			return "Box64 " + problem
		}
		return "Box64: " + problem
	}
	_ = os.Chmod(box, 0o755)
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, box, "--version")
	cmd.Env = append(os.Environ(), "BOX64_NOBANNER=1", "BOX64_LOG=0", "BOX64_DYNACACHE=0")
	out, err := cmd.CombinedOutput()
	if ctx.Err() != nil {
		return "Box64 did not answer within 15 seconds"
	}
	if err != nil {
		line := firstLine(strings.TrimSpace(string(out)))
		if line == "" {
			line = err.Error()
		}
		return "Box64 did not start: " + line
	}
	return ""
}

// ── wine.json ────────────────────────────────────────────────────────────

// wineAllowNewer reports the explicit opt-in to a Wine newer than 10.
func wineAllowNewer() bool {
	v := strings.TrimSpace(os.Getenv("JUKAHUB_WINE_ALLOW_NEWER"))
	return v == "1" || strings.EqualFold(v, "true") || strings.EqualFold(v, "yes")
}

// wineVersionMajor is the leading number of a Wine version ("10.0" → 10); 0
// when there is none.
func wineVersionMajor(v string) int {
	n, digits := 0, 0
	for _, c := range strings.TrimSpace(v) {
		if c < '0' || c > '9' || digits > 4 {
			break
		}
		n = n*10 + int(c-'0')
		digits++
	}
	return n
}

// wineVersionOK accepts a version that is safe as part of a folder name:
// digits first, then digits, letters, dots, dashes and underscores.
func wineVersionOK(v string) bool {
	if v == "" || len(v) > 32 || strings.Contains(v, "..") || wineVersionMajor(v) <= 0 {
		return false
	}
	for _, c := range v {
		switch {
		case c >= '0' && c <= '9', c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c == '.', c == '-', c == '_':
		default:
			return false
		}
	}
	return true
}

// validate checks a Wine build description before anything is fetched.
func (s wineTarballSpec) validate() error {
	if !wineVersionOK(s.Version) {
		return fmt.Errorf("%w: %s names no usable Wine version (%q)", errRelPackUnverified, wineSpecName, s.Version)
	}
	if wineVersionMajor(s.Version) >= 11 && !wineAllowNewer() {
		return fmt.Errorf("the runtime names Wine %s, which aborts on this kernel; JukaHub keeps Wine 10 (JUKAHUB_WINE_ALLOW_NEWER=1 overrides)", s.Version)
	}
	if !strings.HasSuffix(strings.ToLower(s.Asset), ".tar.xz") || s.Asset != sanitizeFileName(s.Asset) || strings.ContainsAny(s.Asset, " \t") {
		return fmt.Errorf("%w: %s names an unexpected Wine archive %q", errRelPackUnverified, wineSpecName, s.Asset)
	}
	if err := validatePatchURL(s.URL); err != nil {
		return fmt.Errorf("%w: %s: %v", errRelPackUnverified, wineSpecName, err)
	}
	if u, err := url.Parse(s.URL); err != nil || path.Base(u.Path) != s.Asset {
		return fmt.Errorf("%w: %s's URL does not end in %s", errRelPackUnverified, wineSpecName, s.Asset)
	}
	if releaseAssetDigest("sha256:"+s.SHA256) == "" {
		return fmt.Errorf("%w: %s has no SHA-256 for %s", errRelPackUnverified, wineSpecName, s.Asset)
	}
	if s.Size < 0 || s.Size > wineMaxTarball {
		return fmt.Errorf("%w: %s gives %s a size of %d bytes", errRelPackUnverified, wineSpecName, s.Asset, s.Size)
	}
	if strings.EqualFold(s.URL, wineNativeSpec.URL) && !strings.EqualFold(s.SHA256, wineNativeSpec.SHA256) {
		return fmt.Errorf("%w: the SHA-256 for %s differs from the one its release publishes", errRelPackUnverified, s.Asset)
	}
	return nil
}

// wineReadSmall reads a file of at most limit bytes.
func wineReadSmall(p string, limit int64) ([]byte, error) {
	f, err := os.Open(p)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > limit {
		return nil, fmt.Errorf("%s is larger than %d bytes", filepath.Base(p), limit)
	}
	return data, nil
}

// wineReadJSON decodes a small JSON file; false when it is missing or
// unreadable.
func wineReadJSON(p string, v any) bool {
	data, err := wineReadSmall(p, 1<<20)
	return err == nil && json.Unmarshal(data, v) == nil
}

// wineWriteJSON writes v as indented JSON.
func wineWriteJSON(p string, v any) error {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(p, append(data, '\n'), 0o644)
}

// readWineTarballSpec reads and checks the pack's wine.json.
func readWineTarballSpec(dir string) (wineTarballSpec, error) {
	var spec wineTarballSpec
	data, err := wineReadSmall(filepath.Join(dir, wineSpecName), 64<<10)
	if err != nil {
		return spec, fmt.Errorf("%w: the runtime pack has no readable %s", errRelPackUnverified, wineSpecName)
	}
	if err := json.Unmarshal(data, &spec); err != nil {
		return spec, fmt.Errorf("%w: the runtime pack's %s is unreadable: %v", errRelPackUnverified, wineSpecName, err)
	}
	spec.Version = strings.TrimSpace(spec.Version)
	spec.Asset = strings.TrimSpace(spec.Asset)
	spec.URL = strings.TrimSpace(spec.URL)
	spec.SHA256 = strings.ToLower(strings.TrimSpace(spec.SHA256))
	return spec, spec.validate()
}

// wineExpectedVersion is the Wine version a runtime install brings: the
// installed pack's, else the one JukaHub pins.
func wineExpectedVersion() string {
	if winePackSupported() {
		if spec, err := readWineTarballSpec(winePackDir()); err == nil {
			return spec.Version
		}
	}
	return wineNativeSpec.Version
}

// ── The unpacked Wine ────────────────────────────────────────────────────

// wineTreeDir is where spec's Wine is unpacked: one folder per version, so a
// new Wine is unpacked beside the old one and the switch is one rename.
func wineTreeDir(spec wineTarballSpec) string {
	return filepath.Join(windowsRuntimeDir(), "wine-"+spec.Version)
}

// wineTreeInstalled reports whether spec's Wine is unpacked, complete, and
// from the tarball spec names.
func wineTreeInstalled(spec wineTarballSpec) bool {
	if !wineVersionOK(spec.Version) {
		return false
	}
	dir := wineTreeDir(spec)
	relPackRecover(dir)
	var marker wineTreeMarker
	if !wineReadJSON(filepath.Join(dir, wineTreeMarkerName), &marker) || !strings.EqualFold(marker.SHA256, spec.SHA256) {
		return false
	}
	return regularFile(filepath.Join(dir, "bin", "wine")) && regularFile(filepath.Join(dir, "bin", "wineserver"))
}

// wineTreeProblem says what an unpacked Wine lacks, "" when it has what a
// launch needs.
func wineTreeProblem(tree string) string {
	wine := filepath.Join(tree, "bin", "wine")
	if !regularFile(wine) {
		return "the Wine archive has no bin/wine"
	}
	if !regularFile(filepath.Join(tree, "bin", "wineserver")) {
		return "the Wine archive has no bin/wineserver"
	}
	if info, err := os.Stat(filepath.Join(tree, "lib", "wine")); err != nil || !info.IsDir() {
		return "the Wine archive has no lib/wine"
	}
	if class, machine, ok := elfArchOfFile(wine); !ok || class != elf.ELFCLASS64 || machine != elf.EM_X86_64 {
		return "the Wine archive's bin/wine is not an x86-64 program"
	}
	return ""
}

// wineCountingReader reports how much of the archive has been read, at most
// four times a second.
type wineCountingReader struct {
	r      io.Reader
	done   int64
	total  int64
	last   time.Time
	report func(done, total int64)
}

func (c *wineCountingReader) Read(p []byte) (int, error) {
	n, err := c.r.Read(p)
	c.done += int64(n)
	if c.report != nil && (err != nil || time.Since(c.last) >= 250*time.Millisecond) {
		c.last = time.Now()
		c.report(c.done, c.total)
	}
	return n, err
}

// wineUnpackTarXz unpacks a .tar.xz into dest with the runtime extractor:
// every entry confined to dest, links made as copies where the card has none.
// report receives the compressed bytes read so far.
func wineUnpackTarXz(ctx context.Context, archive, dest string, report func(done, total int64)) error {
	f, err := os.Open(archive)
	if err != nil {
		return err
	}
	defer f.Close()
	var total int64
	if info, err := f.Stat(); err == nil {
		total = info.Size()
	}
	counted := &wineCountingReader{r: &archiveReader{ctx: ctx, r: f}, total: total, report: report}
	xr, err := xz.NewReader(bufio.NewReaderSize(counted, 1<<20))
	if err != nil {
		return fmt.Errorf("read %s: %w", filepath.Base(archive), err)
	}
	if err := os.MkdirAll(dest, 0o755); err != nil {
		return err
	}
	return extractRuntimeTar(xr, dest)
}

// wineCheckRoom refuses a Wine install the card has no room for: what is
// still to download, plus what the tarball unpacks to.
func wineCheckRoom(base string, spec wineTarballSpec, archive string) error {
	size := spec.Size
	if size <= 0 {
		size = 80 << 20
	}
	have := relPackFileSize(archive)
	if have == 0 {
		have = relPackFileSize(archive + ".part")
	}
	need := size*wineUnpackFactor + relPackSpare
	if rest := size - have; rest > 0 {
		need += rest
	}
	free, err := freeBytes(base)
	if err != nil || free >= need {
		return nil
	}
	return fmt.Errorf("%w · needs %s, has %s", errRelPackNoSpace, formatInstallBytes(need), formatInstallBytes(max64(free, 0)))
}

// wineDownload fetches spec's tarball to dest and checks its SHA-256 and
// size. A download cut off after it made progress is resumed, up to
// wineDownloadTries starts in all; report receives the bytes so far.
func wineDownload(ctx context.Context, client *http.Client, spec wineTarballSpec, dest string, report func(got, total int64)) error {
	matches := func() bool {
		if spec.Size > 0 && relPackFileSize(dest) != spec.Size {
			return false
		}
		got, err := SHA256File(dest)
		return err == nil && strings.EqualFold(got, spec.SHA256)
	}
	if relPackFileSize(dest) > 0 && matches() {
		return nil
	}
	_ = os.Remove(dest)
	stop := make(chan struct{})
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		tick := time.NewTicker(250 * time.Millisecond)
		defer tick.Stop()
		for {
			report(relPackFileSize(dest+".part"), spec.Size)
			select {
			case <-stop:
				return
			case <-tick.C:
			}
		}
	}()
	var err error
	for try := 1; try <= wineDownloadTries; try++ {
		before := relPackFileSize(dest + ".part")
		err = downloadToFile(ctx, client, spec.URL, dest, spec.SHA256, wineMaxTarball)
		if err == nil {
			break
		}
		if strings.Contains(err.Error(), "sha256 mismatch") {
			err = fmt.Errorf("%w: %v", errRelPackUnverified, err)
			break
		}
		if relPackOutOfSpace(err) {
			_ = os.Remove(dest + ".part")
			err = fmt.Errorf("%w · free some space, then try again", errRelPackNoSpace)
			break
		}
		err = relPackNetErr("downloading "+spec.Asset, err)
		lost := errors.Is(err, errRelPackCutOff) || errors.Is(err, errRelPackOffline)
		if !lost || try == wineDownloadTries || relPackFileSize(dest+".part") <= before {
			break
		}
		select {
		case <-ctx.Done():
			err = ctx.Err()
		case <-time.After(2 * time.Second):
			continue
		}
		break
	}
	close(stop)
	wg.Wait()
	if err != nil {
		return err
	}
	if got := relPackFileSize(dest); spec.Size > 0 && got != spec.Size {
		_ = os.Remove(dest)
		return fmt.Errorf("%w: %s is %d bytes, the runtime expects %d", errRelPackUnverified, spec.Asset, got, spec.Size)
	}
	return nil
}

// installWineTree downloads spec's tarball, checks it and unpacks it into its
// versioned folder, which is replaced as a whole. The tarball is deleted
// afterwards. progress (may be nil) receives one-line updates.
func installWineTree(ctx context.Context, client *http.Client, spec wineTarballSpec, progress func(string)) error {
	if progress == nil {
		progress = func(string) {}
	}
	if err := spec.validate(); err != nil {
		return err
	}
	if wineTreeInstalled(spec) {
		return nil
	}
	if client == nil {
		client = relPackClientFn()
	}
	base := windowsRuntimeDir()
	dest := wineTreeDir(spec)
	downloads := filepath.Join(base, "downloads")
	if err := os.MkdirAll(downloads, 0o755); err != nil {
		if disk := relPackDiskErr(err); disk != nil {
			return disk
		}
		return fmt.Errorf("could not create %s: %w", downloads, err)
	}
	archive := filepath.Join(downloads, spec.Asset)
	title := "Wine " + spec.Version
	if err := wineCheckRoom(base, spec, archive); err != nil {
		return err
	}
	err := wineDownload(ctx, client, spec, archive, func(got, total int64) {
		if total > 0 {
			progress(fmt.Sprintf("Downloading %s · %s of %s", title, formatInstallBytes(got), formatInstallBytes(total)))
			return
		}
		progress("Downloading " + title + " · " + formatInstallBytes(got))
	})
	if err != nil {
		return err
	}
	stage := dest + relPackStageSuffix
	_ = os.RemoveAll(stage)
	progress("Unpacking " + title + "…")
	err = wineUnpackTarXz(ctx, archive, stage, func(done, total int64) {
		if total > 0 {
			progress(fmt.Sprintf("Unpacking %s · %d%%", title, done*100/total))
		}
	})
	if err != nil {
		_ = os.RemoveAll(stage)
		if disk := relPackDiskErr(err); disk != nil {
			return disk
		}
		if errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
			return err
		}
		return fmt.Errorf("unpacking %s: %w", spec.Asset, err)
	}
	progress("Checking " + title + "…")
	tree := runtimeArchiveRoot(stage)
	if problem := wineTreeProblem(tree); problem != "" {
		_ = os.RemoveAll(stage)
		_ = os.Remove(archive)
		return fmt.Errorf("%w: %s", errRelPackUnverified, problem)
	}
	marker := wineTreeMarker{wineTarballSpec: spec, InstalledAt: time.Now().UTC().Format(time.RFC3339)}
	if err := wineWriteJSON(filepath.Join(tree, wineTreeMarkerName), marker); err != nil {
		_ = os.RemoveAll(stage)
		if disk := relPackDiskErr(err); disk != nil {
			return disk
		}
		return err
	}
	if err := relPackSwap(tree, dest); err != nil {
		_ = os.RemoveAll(stage)
		if disk := relPackDiskErr(err); disk != nil {
			return disk
		}
		return err
	}
	_ = os.RemoveAll(stage)
	_ = os.Remove(archive)
	logInfo("windowsapps", "Wine %s installed in %s", spec.Version, dest)
	return nil
}

// wineRemoveOldTrees deletes the Wine folders this file unpacked that keep
// no longer names. Callers make sure no Windows program is running.
func wineRemoveOldTrees(keep string) {
	base := windowsRuntimeDir()
	entries, err := os.ReadDir(base)
	if err != nil {
		return
	}
	for _, e := range entries {
		name := e.Name()
		if !e.IsDir() || !strings.HasPrefix(name, "wine-") {
			continue
		}
		dir := filepath.Join(base, name)
		if filepath.Clean(dir) == filepath.Clean(keep) {
			continue
		}
		// Only folders that carry the marker, or the leftovers of an
		// interrupted swap, are JukaHub's to remove.
		leftover := strings.HasSuffix(name, relPackStageSuffix) || strings.HasSuffix(name, relPackOldSuffix)
		if !leftover && !regularFile(filepath.Join(dir, wineTreeMarkerName)) {
			continue
		}
		if err := os.RemoveAll(dir); err != nil {
			logWarn("windowsapps", "could not remove the old Wine in %s: %v", dir, err)
		}
	}
}

// ── JukaHub's runtime as a launch sees it ────────────────────────────────

// wineLayout is JukaHub's own Wine install.
type wineLayout struct {
	Spec    wineTarballSpec
	Tree    string // the unpacked Wine (wine-<version>)
	Box64   string // the pack's box64; "" where Wine runs natively
	X64Lib  string // the x86-64 libraries Box64 needs
	PackTag string // the JukaHub release the pack came from
}

// flavor names the runtime for logs and the setup page.
func (l wineLayout) flavor() string {
	if l.Box64 != "" {
		return "Box64 + Wine " + l.Spec.Version
	}
	return "Wine " + l.Spec.Version
}

func (l wineLayout) wineBin() string { return filepath.Join(l.Tree, "bin", "wine") }

// wineLayoutNow reads JukaHub's own install without downloading or starting
// anything. The problem says what is missing ("" when a launch can use it).
func wineLayoutNow() (wineLayout, string) {
	switch {
	case winePackSupported():
		pack := winePackDir()
		info, ok := relPackRead(pack)
		box := filepath.Join(pack, "box64", "box64")
		if !ok || !regularFile(box) {
			return wineLayout{}, "Box64 is not installed"
		}
		spec, err := readWineTarballSpec(pack)
		if err != nil {
			return wineLayout{}, relPackFriendly(err)
		}
		l := wineLayout{Spec: spec, Tree: wineTreeDir(spec), Box64: box, X64Lib: filepath.Join(pack, "box64", "x64lib"), PackTag: info.Tag}
		if !wineTreeInstalled(spec) {
			return l, "Wine " + spec.Version + " is not installed"
		}
		return l, ""
	case wineNativeSupported():
		l := wineLayout{Spec: wineNativeSpec, Tree: wineTreeDir(wineNativeSpec)}
		if !wineTreeInstalled(wineNativeSpec) {
			return l, "Wine " + wineNativeSpec.Version + " is not installed"
		}
		return l, ""
	}
	return wineLayout{}, "JukaHub has no Windows runtime for this device"
}

// ── Wrappers ─────────────────────────────────────────────────────────────

// wineShellQuote quotes s for a POSIX shell.
func wineShellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// wineShellUnquote undoes wineShellQuote for one assignment's value.
func wineShellUnquote(s string) string {
	s = strings.TrimSpace(s)
	if len(s) >= 2 && strings.HasPrefix(s, "'") && strings.HasSuffix(s, "'") {
		return strings.ReplaceAll(s[1:len(s)-1], `'\''`, "'")
	}
	return s
}

// wineWrapperScript is the wrapper that runs program from the Wine tree
// ("wine" or "wineserver"). With Box64 it sets the library path to the pack's
// x86-64 libraries and Wine's own, hides Box64's banner and keeps its log
// quiet; values the caller already exported win.
func wineWrapperScript(l wineLayout, program string) string {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString(wineWrapperTag + "\n")
	b.WriteString("# Written by JukaHub's Windows runtime installer; rewritten when the runtime changes.\n")
	if l.Box64 != "" {
		b.WriteString("JUKAHUB_BOX64=" + wineShellQuote(l.Box64) + "\n")
	}
	b.WriteString("JUKAHUB_WINE_TREE=" + wineShellQuote(l.Tree) + "\n")
	if l.Box64 != "" {
		b.WriteString("export BOX64_LD_LIBRARY_PATH=" + wineShellQuote(l.X64Lib) + "\":$JUKAHUB_WINE_TREE/lib/wine/x86_64-unix${BOX64_LD_LIBRARY_PATH:+:$BOX64_LD_LIBRARY_PATH}\"\n")
		b.WriteString("export BOX64_PATH=\"$JUKAHUB_WINE_TREE/bin${BOX64_PATH:+:$BOX64_PATH}\"\n")
		b.WriteString("export BOX64_NOBANNER=\"${BOX64_NOBANNER:-1}\"\n")
		b.WriteString("export BOX64_LOG=\"${BOX64_LOG:-0}\"\n")
		b.WriteString(box64WrapperTuning(l.Box64))
	}
	b.WriteString("export WINESERVER=\"${WINESERVER:-$JUKAHUB_WINE_TREE/bin/wineserver}\"\n")
	if l.Box64 != "" {
		b.WriteString("exec \"$JUKAHUB_BOX64\" \"$JUKAHUB_WINE_TREE/bin/" + program + "\" \"$@\"\n")
	} else {
		b.WriteString("exec \"$JUKAHUB_WINE_TREE/bin/" + program + "\" \"$@\"\n")
	}
	return b.String()
}

// box64WrapperScript runs box64 itself with the pack's x86-64 libraries on
// its library path: what a Box64 game profile starts.
func box64WrapperScript(box, x64lib string) string {
	return "#!/bin/sh\n" +
		wineWrapperTag + "\n" +
		"# Written by JukaHub's Windows runtime installer; rewritten when the runtime changes.\n" +
		"JUKAHUB_BOX64=" + wineShellQuote(box) + "\n" +
		"export BOX64_LD_LIBRARY_PATH=" + wineShellQuote(x64lib) + "\"${BOX64_LD_LIBRARY_PATH:+:$BOX64_LD_LIBRARY_PATH}\"\n" +
		"export BOX64_NOBANNER=\"${BOX64_NOBANNER:-1}\"\n" +
		box64WrapperTuning(box) +
		"exec \"$JUKAHUB_BOX64\" \"$@\"\n"
}

// box64WrapperTuning is the part of a wrapper that sets Box64's own defaults,
// each only when the caller (a game profile's env) has not:
//
//   - BOX64_DYNACACHE=0. Box64 0.4.4 turned its DynaCache on by default: it
//     writes up to 2 GB of translated code under $HOME/.cache, and a cache
//     left over from an older Box64 or Wine has made wineboot crash at start
//     (the Armada Box64 project switched it off for that reason). On a card
//     that JukaHub updates by itself, a stale cache is the normal case, so it
//     stays off unless a profile asks for it (BOX64_DYNACACHE=1).
//   - BOX64_RCFILE, when the pack carries box64.box64rc: Box64's per-program
//     settings, which it otherwise reads from /etc/box64.box64rc — a file the
//     handheld does not have.
//
// The rc file's path goes through a plain shell variable: a quoted value
// inside "${VAR:-…}" would keep its quote characters.
func box64WrapperTuning(box string) string {
	var b strings.Builder
	b.WriteString("export BOX64_DYNACACHE=\"${BOX64_DYNACACHE:-0}\"\n")
	if rc := filepath.Join(filepath.Dir(box), "box64.box64rc"); box != "" && regularFile(rc) {
		b.WriteString("JUKAHUB_BOX64_RC=" + wineShellQuote(rc) + "\n")
		b.WriteString("export BOX64_RCFILE=\"${BOX64_RCFILE:-$JUKAHUB_BOX64_RC}\"\n")
	}
	return b.String()
}

// wineWriteIfChanged writes script to p unless p already holds it, through a
// temporary file so a reader never sees half a script.
func wineWriteIfChanged(p, script string) error {
	if old, err := wineReadSmall(p, 64<<10); err == nil && string(old) == script {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	tmp := p + ".new"
	if err := os.WriteFile(tmp, []byte(script), 0o755); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	_ = os.Chmod(tmp, 0o755)
	if err := os.Rename(tmp, p); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

// writeWineWrappers writes bin/wine and bin/wineserver for l.
func writeWineWrappers(l wineLayout) error {
	dir := wineWrapperDir()
	for _, program := range []string{"wine", "wineserver"} {
		if err := wineWriteIfChanged(filepath.Join(dir, program), wineWrapperScript(l, program)); err != nil {
			return err
		}
	}
	return nil
}

// wineWrappersCurrent reports whether bin/wine and bin/wineserver already
// run l.
func wineWrappersCurrent(l wineLayout) bool {
	dir := wineWrapperDir()
	for _, program := range []string{"wine", "wineserver"} {
		data, err := wineReadSmall(filepath.Join(dir, program), 64<<10)
		if err != nil || string(data) != wineWrapperScript(l, program) {
			return false
		}
	}
	return true
}

// wineBox64Wrapper is JukaHub's bin/box64 when the pack is installed (written
// if needed), else "".
func wineBox64Wrapper() string {
	if !winePackSupported() {
		return ""
	}
	box := filepath.Join(winePackDir(), "box64", "box64")
	if !regularFile(box) {
		return ""
	}
	p := filepath.Join(wineWrapperDir(), "box64")
	if err := wineWriteIfChanged(p, box64WrapperScript(box, filepath.Join(winePackDir(), "box64", "x64lib"))); err != nil {
		logWarn("windowsapps", "could not write %s: %v", p, err)
		return ""
	}
	return p
}

// wineReadHead reads the first n bytes of a file as text ("" when it cannot).
func wineReadHead(p string, n int64) string {
	f, err := os.Open(p)
	if err != nil {
		return ""
	}
	defer f.Close()
	data, _ := io.ReadAll(io.LimitReader(f, n))
	return string(data)
}

// wineScriptVar reads NAME='value' from a wrapper JukaHub wrote.
func wineScriptVar(script, name string) string {
	for _, line := range strings.Split(script, "\n") {
		if strings.HasPrefix(line, name+"=") {
			return wineShellUnquote(strings.TrimPrefix(line, name+"="))
		}
	}
	return ""
}

// hangoverWrapperBinary is the program the Hangover installer's wrapper runs
// (its `exec '<binary>' "$@"` line).
func hangoverWrapperBinary(script string) string {
	for _, line := range strings.Split(script, "\n") {
		if strings.HasPrefix(line, "exec ") {
			return wineShellUnquote(strings.TrimSuffix(strings.TrimSpace(strings.TrimPrefix(line, "exec ")), `"$@"`))
		}
	}
	return ""
}

// wineWrapperIsHangover reports a wrapper the Hangover installer wrote.
func wineWrapperIsHangover(p string) bool {
	return strings.Contains(wineReadHead(p, 4096), hangoverWrapperMark)
}

// wineWrapperUsable reports whether the wrapper at p can start Wine here: one
// of JukaHub's own whose Box64 and Wine are still in place, a Hangover
// wrapper whose binary this firmware's loader accepts (its Debian 12 build
// needs a newer glibc than the Smart Pro has), or anything else (a user's own
// script, which JukaHub cannot judge).
func wineWrapperUsable(p string) bool {
	head := wineReadHead(p, 4096)
	switch {
	case strings.Contains(head, wineWrapperTag):
		tree := wineScriptVar(head, "JUKAHUB_WINE_TREE")
		if tree == "" || !regularFile(filepath.Join(tree, "bin", "wine")) {
			return false
		}
		box := wineScriptVar(head, "JUKAHUB_BOX64")
		return box == "" || regularFile(box)
	case strings.Contains(head, hangoverWrapperMark):
		bin := hangoverWrapperBinary(head)
		return bin == "" || nativeLoadProblem(bin) == ""
	}
	return true
}

// wineDropUnusableHangover removes the Hangover runtime an earlier JukaHub
// installed when this firmware cannot load it: about 2.5 GB that can never
// run here. Nothing is removed without that evidence.
func wineDropUnusableHangover() {
	wrapper := filepath.Join(wineWrapperDir(), "wine")
	head := wineReadHead(wrapper, 4096)
	if !strings.Contains(head, hangoverWrapperMark) {
		return
	}
	bin := hangoverWrapperBinary(head)
	dir := filepath.Join(windowsRuntimeDir(), "hangover")
	if bin == "" || !isPathWithin(bin, dir) {
		return
	}
	problem := nativeLoadProblem(bin)
	if problem == "" {
		return
	}
	logWarn("windowsapps", "removing the Hangover runtime in %s, which this firmware cannot start: %s", dir, problem)
	if err := os.RemoveAll(dir); err != nil {
		logWarn("windowsapps", "could not remove %s: %v", dir, err)
		return
	}
	_ = os.Remove(wrapper)
}

// ── Install and update ───────────────────────────────────────────────────

// installWindowsRuntimeCore installs JukaHub's runtime for this device: on
// ARM64 the Box64 pack (when it is missing, or when refresh asks and a newer
// one is published), then the Wine its wine.json names; on x86-64 the pinned
// Wine. The wrappers are rewritten and Wine folders no longer named are
// removed. Callers make sure no Windows program is running.
func installWindowsRuntimeCore(ctx context.Context, client *http.Client, refresh bool, progress func(string)) error {
	if progress == nil {
		progress = func(string) {}
	}
	if client == nil {
		client = relPackClientFn()
	}
	switch {
	case winePackSupported():
		pack := winePackDir()
		info, ok := relPackRead(pack)
		_, specErr := readWineTarballSpec(pack)
		need := !ok || specErr != nil || !regularFile(filepath.Join(pack, "box64", "box64"))
		if !need && refresh {
			progress("Looking for " + winePackTitle + " on GitHub…")
			latest, err := relPackLatest(ctx, client, winePackSpecFor())
			if err != nil {
				return err
			}
			need = relPackNewer(info, latest)
		}
		if need {
			if _, err := relPackInstall(ctx, client, winePackSpecFor(), pack, func(p relPackProgress) {
				progress(p.line(winePackTitle))
			}); err != nil {
				return err
			}
		}
		spec, err := readWineTarballSpec(pack)
		if err != nil {
			return err
		}
		wineDropUnusableHangover()
		if err := installWineTree(ctx, client, spec, progress); err != nil {
			return err
		}
	case wineNativeSupported():
		if err := installWineTree(ctx, client, wineNativeSpec, progress); err != nil {
			return err
		}
	default:
		return errRelPackUnsupported
	}
	layout, problem := wineLayoutNow()
	if problem != "" {
		return errors.New(problem)
	}
	if err := writeWineWrappers(layout); err != nil {
		if disk := relPackDiskErr(err); disk != nil {
			return disk
		}
		return fmt.Errorf("could not write the Wine wrappers: %w", err)
	}
	wineBox64Wrapper()
	wineRemoveOldTrees(layout.Tree)
	return nil
}

// wineProgramsRunning reports a Wine session JukaHub planned, a Windows
// program still starting (its first run prepares Windows for minutes before
// any session or pid exists), or a Windows app or game profile still running:
// replacing the runtime now would pull it from under them.
func wineProgramsRunning() bool {
	if wineSessionsOpen() > 0 || wineLaunchBusy() {
		return true
	}
	windowsAppRunning.mu.Lock()
	apps := len(windowsAppRunning.pids)
	windowsAppRunning.mu.Unlock()
	gameProfileRunning.mu.Lock()
	games := len(gameProfileRunning.pids)
	gameProfileRunning.mu.Unlock()
	return apps > 0 || games > 0
}

// wineRuntimeInUse is the automatic pass's InUse: a program running, or a
// runtime install already in progress.
func wineRuntimeInUse() bool {
	return wineProgramsRunning() || windowsRuntimeInstalling()
}

// wineUpdateCheck is the automatic pass's question: is a newer pack
// published, or does the installed pack name a Wine that is not unpacked
// yet?
func wineUpdateCheck(ctx context.Context, client *http.Client) (bool, string, error) {
	if client == nil {
		client = relPackClientFn()
	}
	info, ok := relPackRead(winePackDir())
	latest, err := relPackLatest(ctx, client, winePackSpecFor())
	if err != nil {
		return false, "", err
	}
	if !ok || relPackNewer(info, latest) {
		return true, latest.Rel.TagName, nil
	}
	if spec, err := readWineTarballSpec(winePackDir()); err == nil && !wineTreeInstalled(spec) {
		return true, "Wine " + spec.Version, nil
	}
	return false, "", nil
}

// wineUpdateInstall brings the runtime forward for the automatic pass, with
// its progress on the setup page's installer line too.
func wineUpdateInstall(ctx context.Context, client *http.Client, progress func(string)) error {
	if !beginWindowsRuntimeInstall("wine", "checking "+winePackTitle) {
		return errRelPackBusy
	}
	defer func() {
		endWindowsRuntimeInstall()
		invalidateWindowsAppsCache()
	}()
	// The pass checked InUse a moment ago; a program started since then is
	// seen here, now that the slot refuses new launches.
	if wineProgramsRunning() {
		logInfo("windowsapps", "a Windows program started; the runtime update waits for the next pass")
		setWindowsRuntimeStatus("The runtime update waits while a Windows program runs", "", false)
		return errRelPackBusy
	}
	err := installWindowsRuntimeCore(ctx, client, true, func(line string) {
		setWindowsRuntimeStatus(line, "", true)
		if progress != nil {
			progress(line)
		}
	})
	if err != nil {
		reason := relPackFriendly(err)
		markWindowsRuntimeFailed("wine", reason)
		setWindowsRuntimeStatus("Windows runtime update failed", reason, false)
		return err
	}
	setWindowsRuntimeStatus("Windows runtime updated", "", false)
	return nil
}

func init() {
	registerEmuRuntimeUpdater(emuRuntimeUpdater{
		Key:       winePackKey,
		Title:     winePackTitle,
		Supported: winePackSupported,
		Installed: func() bool {
			_, ok := relPackRead(winePackDir())
			return ok
		},
		InUse:   wineRuntimeInUse,
		Check:   wineUpdateCheck,
		Install: wineUpdateInstall,
	})
}
