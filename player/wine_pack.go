package main

// wine_pack.go — installing the Windows-app runtime on Linux: Box64 from
// JukaHub's own release pack, Wine 10.0 from Kron4ek's builds, and the small
// wrapper scripts every caller starts Wine through.
//
// Why these pieces (researched 2026-11-11):
//
//   - The Smart Pro runs glibc 2.33 on a 4.9 kernel. Box64 has to be built
//     against a glibc no newer than that, so JukaHub's CI builds it and attaches
//     it to JukaHub's own releases as JukaHub-Wine-linux-arm64.zip. relpack.go
//     installs it: the signed release manifest or GitHub's digest, the pack's
//     own SHA256SUMS, and a probe that starts the staged box64 before anything
//     is replaced.
//   - Wine itself is Kron4ek's vanilla 10.0 "amd64-wow64" build: an x86-64
//     Wine whose WoW64 mode also runs 32-bit Windows programs, with no 32-bit
//     Linux libraries and no Box86. Wine 11.x aborts on the 4.9 kernel
//     ("anon_mmap_alloc: Assertion !(size & host_page_mask)"), so a pack that
//     names Wine 11 or newer is refused unless JUKAHUB_WINE_ALLOW_NEWER=1. The
//     pack does not carry Wine: its wine.json names the release asset with its
//     SHA-256 and size, and JukaHub downloads it from GitHub and checks both.
//   - Box64 needs the x86-64 libgcc_s/libstdc++ the pack carries in
//     box64/x64lib, through BOX64_LD_LIBRARY_PATH. The wrappers written to
//     data/windows-runtime/bin set that up, so resolveWine and every caller
//     that runs "wine" keep working unchanged.
//
// On an x86-64 Linux PC without a Wine of its own, the same Wine 10.0 tarball
// runs natively, pinned below with the checksum its release publishes. Windows
// needs none of this: a .exe runs directly there.

