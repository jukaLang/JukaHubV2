package main

// Published releases may have an empty body or only GitHub's generated "Full
// Changelog" link. Show the comparison's commit titles and descriptions on
// the handheld instead of asking the user to open that link elsewhere.

import (
	"context"
	"encoding/json"
	"fmt"
	"net/url"
	"strings"
)

const githubReleasesAPI = "https://api.github.com/repos/jukaLang/JukaHubV2/releases"
const githubCompareAPI = "https://api.github.com/repos/jukaLang/JukaHubV2/compare/"

type releaseNotesFetch func(context.Context, string) ([]byte, error)

func fetchReleaseNotesURL(ctx context.Context, raw string) ([]byte, error) {
	return fetchBounded(ctx, newPatchClient(), raw, patchMaxMetadata)
}

func validReleaseNotesTag(tag string) bool {
	if tag == "" || len(tag) > 128 {
		return false
	}
	for i := 0; i < len(tag); i++ {
		c := tag[i]
		if c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' ||
			(i > 0 && (c == '.' || c == '-' || c == '_')) {
			continue
		}
		return false
	}
	return true
}

func fetchPublishedReleaseNotes(ctx context.Context, tag string) (string, error) {
	return fetchPublishedReleaseNotesWith(ctx, tag, fetchReleaseNotesURL)
}

func fetchPublishedReleaseNotesWith(ctx context.Context, tag string, fetch releaseNotesFetch) (string, error) {
	if !validReleaseNotesTag(tag) {
		return "", fmt.Errorf("invalid release tag %q", tag)
	}
	data, err := fetch(ctx, githubReleasesAPI+"/tags/"+url.PathEscape(tag))
	if err != nil {
		return "", err
	}
	var rel githubRelease
	if err := json.Unmarshal(data, &rel); err != nil {
		return "", fmt.Errorf("read release %s: %w", tag, err)
	}
	if !strings.EqualFold(rel.TagName, tag) {
		return "", fmt.Errorf("release response did not match %s", tag)
	}
	return publishedReleaseNotesWith(ctx, &rel, fetch)
}

// fillMissingReleaseNotes gives update prompts and the installed changelog the
// same readable notes. A failed fallback must not prevent an update check.
func fillMissingReleaseNotes(ctx context.Context, rel *githubRelease) error {
	return fillMissingReleaseNotesWith(ctx, rel, fetchReleaseNotesURL)
}

func fillMissingReleaseNotesWith(ctx context.Context, rel *githubRelease, fetch releaseNotesFetch) error {
	if rel == nil {
		return nil
	}
	if !validReleaseNotesTag(rel.TagName) {
		return fmt.Errorf("invalid release tag %q", rel.TagName)
	}
	_, _, hasLink := splitFullChangelogLink(rel.Body, rel.TagName)
	if cachedTag, cachedBody := cachedReleaseNotes(); (strings.TrimSpace(rel.Body) == "" || hasLink) &&
		strings.EqualFold(cachedTag, rel.TagName) &&
		cachedBody != "" && !releaseNotesNeedExpansion(cachedBody) {
		rel.Body = cachedBody
		return nil
	}
	body, err := publishedReleaseNotesWith(ctx, rel, fetch)
	if err == nil {
		rel.Body = body
	}
	return err
}

// publishedReleaseNotesWith keeps an authored release body, replaces GitHub's
// comparison footer with its actual commits, and includes the release title.
func publishedReleaseNotesWith(ctx context.Context, rel *githubRelease, fetch releaseNotesFetch) (string, error) {
	body, previous, hasLink := splitFullChangelogLink(rel.Body, rel.TagName)
	if hasLink || body == "" {
		var changes string
		var err error
		if previous != "" {
			changes, err = releaseNotesFromCompareWith(ctx, previous, rel.TagName, fetch)
		} else {
			changes, err = releaseNotesFromCommitsWith(ctx, rel.TagName, fetch)
		}
		if err != nil {
			return "", err
		}
		if body != "" {
			body += "\n\n" + changes
		} else {
			body = changes
		}
	}
	return releaseNotesWithTitle(rel.Name, rel.TagName, body), nil
}

func releaseNotesWithTitle(name, tag, body string) string {
	title := strings.TrimSpace(name)
	if title == "" {
		title = tag
	}
	body = strings.TrimSpace(body)
	if strings.HasPrefix(body, "## "+title+"\n") || body == "## "+title {
		return body
	}
	return "## " + title + "\n\n" + body
}

// splitFullChangelogLink removes the footer generated by GitHub. A valid
// comparison URL supplies its previous tag directly, avoiding another API
// request and keeping the in-app notes aligned with the published comparison.
func splitFullChangelogLink(body, tag string) (clean, previous string, found bool) {
	var kept []string
	for _, line := range strings.Split(body, "\n") {
		if prev, ok := fullChangelogLinkLine(line, tag); ok {
			found = true
			if prev != "" {
				previous = prev
			}
			continue
		}
		kept = append(kept, line)
	}
	return strings.TrimSpace(strings.Join(kept, "\n")), previous, found
}

func fullChangelogLinkLine(line, tag string) (previous string, found bool) {
	line = strings.TrimSpace(line)
	label := strings.TrimSpace(strings.TrimPrefix(line, "**"))
	if !strings.HasPrefix(strings.ToLower(label), "full changelog") ||
		!strings.Contains(strings.ToLower(line), "github.com/jukalang/jukahubv2/compare/") {
		return "", false
	}
	start := strings.Index(strings.ToLower(line), "https://github.com/")
	if start < 0 {
		return "", true
	}
	raw := strings.TrimRight(strings.Fields(line[start:])[0], ")>.,")
	u, err := url.Parse(raw)
	if err != nil || u.Scheme != "https" || !strings.EqualFold(u.Host, "github.com") {
		return "", true
	}
	const pathPrefix = "/jukaLang/JukaHubV2/compare/"
	if !strings.HasPrefix(strings.ToLower(u.Path), strings.ToLower(pathPrefix)) {
		return "", true
	}
	parts := strings.Split(u.Path[len(pathPrefix):], "...")
	if len(parts) != 2 || !validReleaseNotesTag(parts[0]) ||
		!strings.EqualFold(parts[1], tag) || !sameReleaseTagFamily(tag, parts[0]) {
		return "", true
	}
	return parts[0], true
}

func releaseNotesNeedExpansion(body string) bool {
	// Earlier builds synthesized this heading from commit subjects only. Fetch
	// those notes again so their descriptions appear too.
	if strings.HasPrefix(strings.TrimSpace(body), "## Changes since ") {
		return true
	}
	if !strings.Contains(body, "/compare/") {
		return false
	}
	_, _, found := splitFullChangelogLink(body, "")
	return found
}

func releaseNotesFromCommitsWith(ctx context.Context, tag string, fetch releaseNotesFetch) (string, error) {
	previous, err := previousPublishedReleaseTagWith(ctx, tag, fetch)
	if err != nil {
		return "", err
	}
	return releaseNotesFromCompareWith(ctx, previous, tag, fetch)
}

func releaseNotesFromCompareWith(ctx context.Context, previous, tag string, fetch releaseNotesFetch) (string, error) {
	type commit struct {
		Commit struct {
			Message string `json:"message"`
		} `json:"commit"`
	}
	var messages []string
	var total int
	for page := 1; page <= 3; page++ {
		raw := fmt.Sprintf("%s%s...%s?per_page=100&page=%d", githubCompareAPI,
			url.PathEscape(previous), url.PathEscape(tag), page)
		data, err := fetch(ctx, raw)
		if err != nil {
			return "", err
		}
		var comparison struct {
			TotalCommits int      `json:"total_commits"`
			Commits      []commit `json:"commits"`
		}
		if err := json.Unmarshal(data, &comparison); err != nil {
			return "", fmt.Errorf("read commits for %s: %w", tag, err)
		}
		total = comparison.TotalCommits
		for _, c := range comparison.Commits {
			message := strings.TrimSpace(c.Commit.Message)
			if message != "" {
				messages = append(messages, message)
			}
		}
		if len(comparison.Commits) < 100 || page*100 >= total {
			break
		}
	}
	var out strings.Builder
	fmt.Fprintf(&out, "### Full changelog\n\nChanges since %s\n\n", previous)
	if len(messages) == 0 {
		out.WriteString("No source changes were recorded between these releases.")
	} else {
		for _, message := range messages {
			parts := strings.SplitN(message, "\n", 2)
			fmt.Fprintf(&out, "- %s\n", strings.TrimSpace(parts[0]))
			if len(parts) == 2 && strings.TrimSpace(parts[1]) != "" {
				fmt.Fprintf(&out, "%s\n", strings.TrimSpace(parts[1]))
			}
			out.WriteString("\n")
		}
	}
	if total > len(messages) {
		fmt.Fprintf(&out, "\nShowing %d of %d commits.", len(messages), total)
	}
	return strings.TrimSpace(out.String()), nil
}

func previousPublishedReleaseTagWith(ctx context.Context, tag string, fetch releaseNotesFetch) (string, error) {
	found := false
	for page := 1; page <= 50; page++ {
		raw := fmt.Sprintf("%s?per_page=100&page=%d", githubReleasesAPI, page)
		data, err := fetch(ctx, raw)
		if err != nil {
			return "", err
		}
		var releases []struct {
			TagName string `json:"tag_name"`
		}
		if err := json.Unmarshal(data, &releases); err != nil {
			return "", fmt.Errorf("read release list: %w", err)
		}
		for _, rel := range releases {
			if !found {
				found = strings.EqualFold(rel.TagName, tag)
				continue
			}
			if validReleaseNotesTag(rel.TagName) && sameReleaseTagFamily(tag, rel.TagName) {
				return rel.TagName, nil
			}
		}
		if len(releases) < 100 {
			break
		}
	}
	return "", fmt.Errorf("no preceding published release found for %s", tag)
}

func sameReleaseTagFamily(a, b string) bool {
	if strings.HasPrefix(a, "JukaHub-") {
		return strings.HasPrefix(b, "JukaHub-")
	}
	if strings.HasPrefix(a, "v") {
		return strings.HasPrefix(b, "v")
	}
	return true
}
