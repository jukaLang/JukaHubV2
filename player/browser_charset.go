package main

// browser_charset.go — what the Internet browser does with a response body
// before its parser sees it: decode a legacy character set to UTF-8, and turn
// a plain-text, JSON or XML file, or a bare image address, into a small page
// the reader can draw.
//
// Every byte used to be read as UTF-8, so a page served in windows-1251,
// KOI8-R, ISO-8859-1 or any other single-byte charset drew as a wall of
// replacement characters; and every response that was not HTML — a .txt file,
// an API's JSON, a link straight to a picture — stopped at a "This address is
// a … file" card. The multi-byte East Asian charsets (Shift_JIS, EUC-JP, GBK,
// Big5, EUC-KR) need large tables and are still passed through unchanged.

import (
	"bytes"
	"encoding/json"
	htmlstd "html"
	"net/url"
	"path"
	"strings"
	"unicode/utf16"
	"unicode/utf8"
)

// browserDecodeBody returns body as UTF-8. contentType is the response's
// Content-Type header; sniff lets the document's own <meta charset> or XML
// declaration name the charset when the header does not.
func browserDecodeBody(body []byte, contentType string, sniff bool) []byte {
	if len(body) == 0 {
		return body
	}
	// A byte-order mark outranks every declaration, as it does in a browser.
	switch {
	case bytes.HasPrefix(body, []byte{0xEF, 0xBB, 0xBF}):
		return body[3:]
	case len(body) >= 2 && body[0] == 0xFF && body[1] == 0xFE:
		return brwDecodeUTF16(body[2:], false)
	case len(body) >= 2 && body[0] == 0xFE && body[1] == 0xFF:
		return brwDecodeUTF16(body[2:], true)
	}
	label := brwCharsetParam(contentType)
	fromHeader := label != ""
	if !fromHeader && sniff {
		label = brwSniffCharset(body)
	}
	switch label {
	case "utf-16be":
		if fromHeader {
			return brwDecodeUTF16(body, true)
		}
		label = "utf-8" // a <meta> cannot honestly say UTF-16: it was readable as ASCII
	case "utf-16", "utf-16le":
		if fromHeader {
			return brwDecodeUTF16(body, false)
		}
		label = "utf-8"
	}
	table := brwCharsetTables[label]
	switch {
	case label == "" || label == "utf-8" || label == "utf8" || label == "unicode-1-1-utf-8":
		if label == "" && !brwValidUTF8(body) && !brwMostlyUTF8(body) {
			// No declaration and not UTF-8: windows-1252 is what a browser in
			// an English locale assumes. A UTF-8 page with the odd broken byte
			// stays UTF-8 — re-reading it all as windows-1252 would turn every
			// accented letter into two.
			return brwDecodeSingleByte(body, &brwCSWindows1252)
		}
		return body
	case table == nil:
		return body // a charset this build has no table for
	case brwHasHighBytes(body) && brwValidUTF8(body):
		// Declared single-byte but the high bytes form valid UTF-8, which
		// legacy text practically never does: the declaration is stale (a CMS
		// moved to UTF-8 and kept its old <meta>).
		return body
	}
	return brwDecodeSingleByte(body, table)
}

// brwCharsetParam reads the charset parameter of a Content-Type header.
func brwCharsetParam(contentType string) string {
	lower := strings.ToLower(contentType)
	i := strings.Index(lower, "charset=")
	if i < 0 {
		return ""
	}
	return brwCleanCharsetLabel(lower[i+len("charset="):])
}

// brwCleanCharsetLabel trims a label read out of a header or attribute: quotes,
// spaces and whatever parameter follows it.
func brwCleanCharsetLabel(v string) string {
	v = strings.TrimSpace(v)
	v = strings.TrimLeft(v, `"'`)
	if end := strings.IndexAny(v, `"'; ,>`); end >= 0 {
		v = v[:end]
	}
	return strings.ToLower(strings.TrimSpace(v))
}

// brwSniffCharset finds the charset a document declares near its top: an XML
// declaration's encoding, <meta charset>, or a <meta http-equiv="Content-Type">
// content attribute. Browsers look at the first 1024 bytes; pages with a long
// <head> of inline scripts push the tag further, so this reads a little more.
func brwSniffCharset(body []byte) string {
	head := body
	if len(head) > 8192 {
		head = head[:8192]
	}
	src := string(head)
	lower := asciiLower(src)
	if strings.HasPrefix(lower, "<?xml") {
		if end := strings.Index(lower, "?>"); end > 0 {
			decl := lower[:end]
			if i := strings.Index(decl, "encoding="); i >= 0 {
				if label := brwCleanCharsetLabel(decl[i+len("encoding="):]); label != "" {
					return label
				}
			}
		}
	}
	for from := 0; from < len(lower); {
		i := strings.Index(lower[from:], "<meta")
		if i < 0 {
			break
		}
		i += from
		end := findTextBrowserTagEnd(src, i+len("<meta"))
		if end < 0 {
			break
		}
		tag := src[i+1 : end]
		from = end + 1
		if cs := brwCleanCharsetLabel(htmlAttrValue(htmlTagAttribute(tag, "charset"))); cs != "" {
			return cs
		}
		if strings.EqualFold(strings.TrimSpace(htmlTagAttribute(tag, "http-equiv")), "content-type") {
			if cs := brwCharsetParam(htmlAttrValue(htmlTagAttribute(tag, "content"))); cs != "" {
				return cs
			}
		}
	}
	return ""
}

// brwValidUTF8 is utf8.Valid that forgives a character cut off at the very
// end: a page longer than the reader's limit is truncated mid-byte-sequence.
func brwValidUTF8(b []byte) bool {
	if utf8.Valid(b) {
		return true
	}
	for cut := 1; cut <= 3 && cut < len(b); cut++ {
		if !utf8.FullRune(b[len(b)-cut:]) && utf8.Valid(b[:len(b)-cut]) {
			return true
		}
	}
	return false
}

// brwMostlyUTF8 reports whether b's non-ASCII bytes are mostly well-formed
// UTF-8 sequences: at least one multi-byte character, and no more invalid
// bytes than such characters.
func brwMostlyUTF8(b []byte) bool {
	multi, invalid := 0, 0
	for i := 0; i < len(b); {
		if b[i] < 0x80 {
			i++
			continue
		}
		r, size := utf8.DecodeRune(b[i:])
		if r == utf8.RuneError && size <= 1 {
			invalid++
			i++
			continue
		}
		multi++
		i += size
	}
	return multi > 0 && multi >= invalid
}

func brwHasHighBytes(b []byte) bool {
	for _, c := range b {
		if c >= 0x80 {
			return true
		}
	}
	return false
}

func brwDecodeSingleByte(b []byte, table *[128]uint16) []byte {
	out := make([]byte, 0, len(b)+len(b)/2)
	for _, c := range b {
		if c < 0x80 {
			out = append(out, c)
			continue
		}
		out = utf8.AppendRune(out, rune(table[c-0x80]))
	}
	return out
}

func brwDecodeUTF16(b []byte, bigEndian bool) []byte {
	units := make([]uint16, 0, len(b)/2)
	for i := 0; i+1 < len(b); i += 2 {
		if bigEndian {
			units = append(units, uint16(b[i])<<8|uint16(b[i+1]))
		} else {
			units = append(units, uint16(b[i+1])<<8|uint16(b[i]))
		}
	}
	return []byte(string(utf16.Decode(units)))
}

// What the browser can show for a response, by its media type.
type brwDocKind int

const (
	brwDocHTML  brwDocKind = iota // a web page
	brwDocText                    // plain text, JSON, XML, CSS, scripts: shown as text
	brwDocImage                   // a picture: shown on a page of its own
	brwDocOther                   // anything else: the "can't show this file" card
)

// brwDocumentKind sorts a lower-case media type (no parameters). A response
// without one is read as a page, as before.
func brwDocumentKind(mediaType string) brwDocKind {
	switch {
	case mediaType == "" || strings.Contains(mediaType, "html"):
		return brwDocHTML
	case mediaType == "text/event-stream":
		return brwDocOther // a stream that never ends, not a file to read
	case strings.HasPrefix(mediaType, "image/"):
		return brwDocImage
	case strings.HasPrefix(mediaType, "text/"),
		strings.HasSuffix(mediaType, "+json"), strings.HasSuffix(mediaType, "+xml"),
		mediaType == "application/json", mediaType == "application/xml",
		mediaType == "application/javascript", mediaType == "application/x-javascript",
		mediaType == "application/ecmascript", mediaType == "application/x-ndjson",
		mediaType == "application/x-sh", mediaType == "application/toml",
		mediaType == "application/yaml", mediaType == "application/x-yaml":
		return brwDocText
	}
	return brwDocOther
}

// brwFileTitle names a file page after the last part of its address.
func brwFileTitle(u *url.URL) string {
	name := path.Base(u.Path)
	if unescaped, err := url.PathUnescape(name); err == nil {
		name = unescaped
	}
	if name == "" || name == "." || name == "/" {
		name = u.Hostname()
	}
	return name
}

// brwImageDocument is the page drawn for an address that is a picture. The
// picture itself is fetched by the ordinary image pass, with an image
// request's headers and limits; the document request is not read.
func brwImageDocument(u *url.URL) []byte {
	title := htmlstd.EscapeString(brwFileTitle(u))
	src := htmlstd.EscapeString(u.String())
	return []byte(`<!DOCTYPE html><html><head><title>` + title + `</title></head>` +
		`<body style="margin:0;padding:8px;text-align:center">` +
		`<img src="` + src + `" alt="` + title + `" style="max-width:100%;height:auto">` +
		`</body></html>`)
}

// brwTextDocument is the page drawn for a text file: its text, escaped, in a
// wrapping <pre>. Compact JSON — one long line from an API — is indented so it
// can be read.
//
// The text is cut to brwMaxTextFileBytes first (the reader keeps far less
// text than that per page anyway), and truncated reports the cut.
func brwTextDocument(text []byte, u *url.URL, mediaType string) (page []byte, truncated bool) {
	if len(text) > brwMaxTextFileBytes {
		cut := brwMaxTextFileBytes
		for cut > 0 && !utf8.RuneStart(text[cut]) {
			cut--
		}
		text, truncated = text[:cut], true
	}
	// Indenting multiplies the size by the nesting depth, so a small body of
	// thousands of nested brackets would grow to hundreds of megabytes.
	if !truncated && strings.Contains(mediaType, "json") && brwJSONDepth(text) <= 64 {
		var pretty bytes.Buffer
		if json.Indent(&pretty, text, "", "  ") == nil && pretty.Len() <= 2*brwMaxTextFileBytes {
			text = pretty.Bytes()
		}
	}
	var b bytes.Buffer
	b.Grow(len(text) + len(text)/8 + 256)
	b.WriteString(`<!DOCTYPE html><html><head><title>`)
	b.WriteString(htmlstd.EscapeString(brwFileTitle(u)))
	b.WriteString(`</title></head><body style="margin:0;padding:12px">`)
	b.WriteString(`<pre style="white-space:pre-wrap;margin:0">`)
	for _, c := range text {
		switch c {
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '&':
			b.WriteString("&amp;")
		default:
			b.WriteByte(c)
		}
	}
	b.WriteString(`</pre></body></html>`)
	return b.Bytes(), truncated
}

// brwMaxTextFileBytes is how much of a text file is turned into a page.
const brwMaxTextFileBytes = 2 << 20

// brwJSONDepth is the deepest bracket nesting in a JSON text, outside strings.
func brwJSONDepth(text []byte) int {
	depth, deepest, inString, escaped := 0, 0, false, false
	for _, c := range text {
		switch {
		case inString:
			switch {
			case escaped:
				escaped = false
			case c == '\\':
				escaped = true
			case c == '"':
				inString = false
			}
		case c == '"':
			inString = true
		case c == '[' || c == '{':
			depth++
			if depth > deepest {
				deepest = depth
			}
		case c == ']' || c == '}':
			depth--
		}
	}
	return deepest
}

