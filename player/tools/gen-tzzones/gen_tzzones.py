#!/usr/bin/env python3
"""Generate player/tzzones.go: the zone table the time-zone picker lists.

Go can load a zone by name (time.LoadLocation, with the embedded time/tzdata)
but cannot list the zones it knows, so the picker reads a static table. It is
every zone of zone.tab (one per country and region: Europe/Amsterdam,
Europe/Oslo and Asia/Kuala_Lumpur included, which zone1970.tab folds into a
neighbour), any zone1970.tab adds, and "UTC", sorted by name, each with its
country (iso3166.tab) and zone.tab's note, so "germany" finds Europe/Berlin
and "eastern" America/New_York. A second table lists the old and alternative
names (the links in tzdata.zi: Asia/Calcutta, Europe/Kiev, US/Eastern) with
the zone each stands for: the picker searches them and marks the zone in force
when it goes by one of them.

Usage (from the repository root, on any machine with the tzdata package):

    python3 player/tools/gen-tzzones/gen_tzzones.py \
        [--zoneinfo /usr/share/zoneinfo] [--out player/tzzones.go]

Re-run it when the IANA database adds or retires a zone, and keep the Go
toolchain's time/tzdata at least as new (datetime_test.go loads every name).
"""

import argparse
import os
import sys


def read_tab(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            rows.append(line.split("\t"))
    return rows


def tzdata_version(zoneinfo):
    path = os.path.join(zoneinfo, "tzdata.zi")
    try:
        with open(path, encoding="utf-8") as f:
            first = f.readline().strip()
    except OSError:
        return "unknown"
    if first.startswith("# version "):
        return first[len("# version "):]
    return "unknown"


def go_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--zoneinfo", default="/usr/share/zoneinfo")
    ap.add_argument("--out", default=os.path.join("player", "tzzones.go"))
    args = ap.parse_args()

    countries = {}
    for row in read_tab(os.path.join(args.zoneinfo, "iso3166.tab")):
        if len(row) >= 2:
            countries[row[0]] = row[1]

    def described(codes, note):
        text = ", ".join(countries.get(c, c) for c in codes)
        if note:
            text += " · " + note
        return text

    # zone.tab: one zone per country and region, the names people know.
    zones = {}
    for row in read_tab(os.path.join(args.zoneinfo, "zone.tab")):
        if len(row) < 3:
            continue
        zones[row[2]] = described([row[0]], row[3] if len(row) > 3 else "")
    # zone1970.tab: anything canonical zone.tab does not list.
    for row in read_tab(os.path.join(args.zoneinfo, "zone1970.tab")):
        if len(row) < 3 or row[2] in zones:
            continue
        zones[row[2]] = described(row[0].split(","), row[3] if len(row) > 3 else "")
    zones["UTC"] = "Coordinated Universal Time"
    if len(zones) < 300:
        sys.exit("only %d zones read; is %s a tzdata directory?" % (len(zones), args.zoneinfo))

    # Links (old and alternative names) from tzdata.zi's "L TARGET NAME"
    # lines; the ones that are rows themselves need no alias. The universal
    # zones all stand for the UTC row.
    universal = {"Etc/UTC", "Etc/GMT", "Etc/UCT", "Etc/Universal", "Etc/Zulu",
                 "Etc/Greenwich", "Etc/GMT0", "Etc/GMT+0", "Etc/GMT-0"}
    aliases = {name: "UTC" for name in universal}
    links = 0
    with open(os.path.join(args.zoneinfo, "tzdata.zi"), encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if len(parts) != 3 or parts[0] != "L":
                continue
            links += 1
            target, name = parts[1], parts[2]
            if name in zones:
                continue
            if target in zones:
                aliases[name] = target
            elif target in universal:
                aliases[name] = "UTC"
    if links < 50:
        sys.exit("only %d links read from tzdata.zi" % links)
    for name in list(aliases):
        if name in zones:
            del aliases[name]

    version = tzdata_version(args.zoneinfo)
    out = []
    out.append("package main")
    out.append("")
    out.append("// tzzones.go — GENERATED by tools/gen-tzzones/gen_tzzones.py from the IANA")
    out.append("// time zone database %s (zone.tab, zone1970.tab, iso3166.tab, tzdata.zi)." % version)
    out.append("// Do not edit by hand: re-run the script when the database adds or retires a")
    out.append("// zone.")
    out.append("//")
    out.append("// Go can load a zone by name but cannot list them, so the time-zone picker")
    out.append("// (tzpicker.go) reads these tables: every zone of zone.tab (one per country")
    out.append("// and region) and zone1970.tab plus UTC, sorted by name, with its country and")
    out.append("// note for search and the second line; and the old and alternative names")
    out.append("// with the zone each stands for.")
    out.append("")
    out.append("// tzZone is one zone the picker offers.")
    out.append("type tzZone struct {")
    out.append("\tName      string // IANA name: \"Europe/Berlin\"")
    out.append("\tCountries string // where it is used: \"Germany · most of Germany\"")
    out.append("}")
    out.append("")
    out.append("// tzZones is sorted by Name (datetime_test.go holds it to that).")
    out.append("var tzZones = [...]tzZone{")
    for name in sorted(zones):
        out.append("\t{%s, %s}," % (go_string(name), go_string(zones[name])))
    out.append("}")
    out.append("")
    out.append("// tzAlias is an old or alternative zone name and the listed zone it stands")
    out.append("// for.")
    out.append("type tzAlias struct {")
    out.append("\tAlias string // \"Asia/Calcutta\"")
    out.append("\tZone  string // \"Asia/Kolkata\"")
    out.append("}")
    out.append("")
    out.append("// tzAliases is sorted by Alias (datetime_test.go holds it to that).")
    out.append("var tzAliases = [...]tzAlias{")
    for name in sorted(aliases):
        out.append("\t{%s, %s}," % (go_string(name), go_string(aliases[name])))
    out.append("}")
    text = "\n".join(out) + "\n"
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %d zones and %d aliases (tzdata %s) to %s" % (len(zones), len(aliases), version, args.out))


if __name__ == "__main__":
    main()
