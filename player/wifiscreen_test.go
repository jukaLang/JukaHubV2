// TestWiFiScrRowMeta pins each row's second line: the connection with its
// address, work in flight on that network, then saved / secured / open with
// the signal in words.
func TestWiFiScrRowMeta(t *testing.T) {
	status := wifiStatus{State: wifiCompleteState, SSID: "HomeNet", IP: "192.168.1.20", Connected: true}
	cases := []struct {
		n          wifiNetwork
		busy, want string
	}{
		{wifiNetwork{SSID: "HomeNet", Signal: -47, Secured: true, Saved: true, Active: true}, "", "Connected · 192.168.1.20"},
		{wifiNetwork{SSID: "Office", Signal: -47, Secured: true, Saved: true}, "", "Saved · Excellent signal"},
		{wifiNetwork{SSID: "Lab", Signal: -66, Secured: true}, "", "Secured · Good signal"},
		{wifiNetwork{SSID: "Cafe", Signal: -90}, "", "Open network · Weak signal"},
		{wifiNetwork{SSID: "Cafe", Signal: -90}, "Connecting to Cafe…", "Connecting to Cafe…"},
		{wifiNetwork{SSID: "Office", Signal: -72, Saved: true}, "Connecting to Cafe…", "Saved · Fair signal"},
	}
	for _, c := range cases {
		if got := wifiScrRowMeta(c.n, status, c.busy); got != c.want {
			t.Errorf("%s (busy %q): %q, want %q", c.n.SSID, c.busy, got, c.want)
		}
	}
	noIP := wifiStatus{State: wifiCompleteState, SSID: "HomeNet", Connected: true}
	if got := wifiScrRowMeta(wifiNetwork{SSID: "HomeNet", Active: true}, noIP, ""); got != "Connected" {
		t.Errorf("connected without an address = %q", got)
	}
}

// TestWiFiScrDetailsText: the connected network's details carry the live link
// facts once they are read; another network's say what it is and whether it
// is saved.
func TestWiFiScrDetailsText(t *testing.T) {
	wifiScrPinMeter(t, 4)
	status := wifiStatus{State: wifiCompleteState, SSID: "HomeNet", IP: "192.168.1.20", Connected: true}
	home := wifiNetwork{SSID: "HomeNet", BSSID: "aa:bb:cc:dd:ee:01", Signal: -47, Secured: true, Saved: true, Active: true}

	read := wifiScrDetailsSample{
		ssid:    "HomeNet",
		signal:  wifiSignalSample{RSSI: -52, FreqMHz: 5180, LinkKbps: 433300},
		gateway: "192.168.1.1",
		dns:     []string{"1.1.1.1", "8.8.8.8"},
		at:      time.Now(),
	}
	text := wifiScrDetailsText(home, status, read)
	for _, want := range []string{
		"Status:     Connected",
		"Signal:     -52 dBm · excellent signal",
		"Security:   Password protected",
		"Saved:      Yes",
		"IP address: 192.168.1.20",
		"Gateway:    192.168.1.1",
		"DNS:        1.1.1.1, 8.8.8.8",
		"Frequency:  5180 MHz (5 GHz)",
		"Link speed: 433 Mbit/s",
		"BSSID:      aa:bb:cc:dd:ee:01",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("details are missing %q:\n%s", want, text)
		}
	}

	// Before the read lands the sheet says so instead of showing blanks.
	pending := wifiScrDetailsText(home, status, wifiScrDetailsSample{})
	for _, want := range []string{"Signal:     -47 dBm", "Gateway:    Reading…", "DNS:        Reading…"} {
		if !strings.Contains(pending, want) {
			t.Errorf("pending details are missing %q:\n%s", want, pending)
		}
	}
	if strings.Contains(pending, "Frequency:") {
		t.Errorf("pending details invent a frequency:\n%s", pending)
	}

	// No route read: the usual router address, marked as a guess.
	guess := wifiScrDetailsText(home, status, wifiScrDetailsSample{ssid: "HomeNet", at: time.Now()})
	if !strings.Contains(guess, "Gateway:    192.168.1.1 (usual router address)") {
		t.Errorf("gateway guess missing:\n%s", guess)
	}
	wantDNS := "DNS:        Not reported"
	if runtime.GOOS == "windows" {
		wantDNS = "DNS:        Set by Windows"
	}
	if !strings.Contains(guess, wantDNS) {
		t.Errorf("DNS line = %q missing:\n%s", wantDNS, guess)
	}

	cafe := wifiScrDetailsText(wifiNetwork{SSID: "Cafe", Signal: -82}, status, read)
	for _, want := range []string{"Status:     In range", "Security:   Open", "Saved:      No"} {
		if !strings.Contains(cafe, want) {
			t.Errorf("open network details are missing %q:\n%s", want, cafe)
		}
	}
	for _, gone := range []string{"IP address:", "Gateway:", "BSSID:"} {
		if strings.Contains(cafe, gone) {
			t.Errorf("open network details show %q:\n%s", gone, cafe)
		}
	}
	if office := wifiScrDetailsText(wifiNetwork{SSID: "Office", Signal: -66, Saved: true, Secured: true}, status, read); !strings.Contains(office, "Status:     Saved — in range") {
		t.Errorf("saved network status missing:\n%s", office)
	}
}

// TestWiFiScrDetailsSheetOffersTheRightActions: the connected network can be
// reconnected, disconnected or forgotten; a saved one joined or forgotten; an
// open one joined; one that left the list only closed.
func TestWiFiScrDetailsSheetOffersTheRightActions(t *testing.T) {
	wifiScrTestPage(t)
	open := func(ssid string) {
		wifiScr.sheetMode, wifiScr.sheetSSID = wifiScrSheetDetails, ssid
		wifiScr.sheetKey = wifiScrSheetKey{}
		wifiScr.sheet.open = true
		wifiScrSyncSheet()
	}
	cases := []struct{ ssid, subtitle, pills string }{
		{"HomeNet", "Connected", "reconnect,disconnect,forget,close"},
		{"Office", "Saved network", "connect,forget,close"},
		{"Cafe", "Not connected", "connect,close"},
		{"Gone", "Out of range", "close"},
	}
	for _, c := range cases {
		open(c.ssid)
		s := &wifiScr.sheet
		if s.title != c.ssid || s.subtitle != c.subtitle {
			t.Errorf("%s sheet = %q / %q, want %q", c.ssid, s.title, s.subtitle, c.subtitle)
		}
		if got := wifiScrPills(); got != c.pills {
			t.Errorf("%s pills = %s, want %s", c.ssid, got, c.pills)
		}
		if s.text == "" || s.hint == "" {
			t.Errorf("%s sheet has no report or no hint", c.ssid)
		}
	}

	// The first Forget arms, and the sheet says the next press confirms.
	wifiPanel.cursor = 1
	open("Office")
	wifiScrSheetAction("forget")
	if wifiPanel.confirmForget != "Office" || !wifiScr.sheet.open {
		t.Fatalf("the first Forget did not arm (%q, open %v)", wifiPanel.confirmForget, wifiScr.sheet.open)
	}
	wifiScrSyncSheet()
	if label := wifiScr.sheet.pills[1].label; label != "Forget? Press again" {
		t.Fatalf("armed Forget reads %q", label)
	}
	// Closing the sheet disarms it.
	wifiScrCloseSheet()
	if wifiPanel.confirmForget != "" || wifiScr.sheet.open {
		t.Fatal("closing the sheet left the forget armed")
	}
}

// TestWiFiScrSecondForgetRemovesTheNetwork: the confirming press starts the
// removal and the sheet makes way for the list.
func TestWiFiScrSecondForgetRemovesTheNetwork(t *testing.T) {
	wifiScrTestPage(t)
	calls := stubWiFi(t, func(stdin, name string, args []string) (string, error) {
		switch wifiStubCommand(args) {
		case "list_networks":
			return "network id / ssid / bssid / flags\n0\tHomeNet\tany\t[CURRENT]\n1\tOffice\tany\t\n", nil
		case "status":
			return "wpa_state=COMPLETED\nssid=HomeNet\nip_address=192.168.1.20\n", nil
		}
		return "OK\n", nil
	})
	// The worker finishes before the stub is put back.
	t.Cleanup(wifiSettleForTest)

	wifiPanel.cursor = 1
	wifiScr.sheetMode, wifiScr.sheetSSID, wifiScr.sheet.open = wifiScrSheetDetails, "Office", true
	wifiScrSheetAction("forget")
	wifiScrSheetAction("forget")
	if wifiScr.sheet.open || wifiScr.sheetMode != wifiScrSheetNone {
		t.Fatal("the confirming Forget left the sheet over a network that is going away")
	}
	if !wifiPanel.busy {
		t.Fatal("the confirming Forget started no work")
	}
	waitForWiFiIdle(t)
	removed := false
	for _, c := range *calls {
		if wifiStubCommand(c.args) == "remove_network" {
			removed = true
		}
	}
	if !removed {
		t.Fatalf("Forget never removed the network: %+v", *calls)
	}
}

// TestWiFiScrKeysWalkTheListAndTheHeader drives the page from the keyboard.
func TestWiFiScrKeysWalkTheListAndTheHeader(t *testing.T) {
	config := wifiScrTestPage(t)
	key := func(sym sdl.Keycode) bool { return wifiScrKey(pressKey(sym), config) }

	if !key(sdl.K_DOWN) || wifiPanel.cursor != 1 {
		t.Fatalf("Down left the cursor on %d", wifiPanel.cursor)
	}
	if !key(sdl.K_UP) || wifiPanel.cursor != 0 || wifiScr.zone != 0 {
		t.Fatalf("Up left the cursor on %d (zone %d)", wifiPanel.cursor, wifiScr.zone)
	}
	// Up from the top row reaches the header controls, starting at the right.
	if !key(sdl.K_UP) || wifiScr.zone != 1 || wifiScr.ctrls[wifiScr.ctrl].id != "radio" {
		t.Fatalf("Up from the top row: zone %d control %d, want the radio switch", wifiScr.zone, wifiScr.ctrl)
	}
	if !key(sdl.K_LEFT) || wifiScr.ctrls[wifiScr.ctrl].id != "diag" {
		t.Fatalf("Left in the header focused %q, want Diagnostics", wifiScr.ctrls[wifiScr.ctrl].id)
	}
	if key(sdl.K_UP) {
		t.Fatal("Up from the header was swallowed; it belongs to the top bar")
	}
	if !key(sdl.K_DOWN) || wifiScr.zone != 0 {
		t.Fatal("Down from the header did not come back to the list")
	}

	// X opens the details of the network under the cursor, and the sheet takes
	// the keys until Escape.
	key(sdl.K_DOWN)
	if !key(sdl.K_x) || !wifiScr.sheet.open || wifiScr.sheetSSID != "Office" {
		t.Fatalf("X opened %q (open %v), want Office's details", wifiScr.sheetSSID, wifiScr.sheet.open)
	}
	if !key(sdl.K_RIGHT) || wifiScr.sheet.focus != 1 || wifiPanel.cursor != 1 {
		t.Fatalf("Right in the sheet: pill %d, cursor %d", wifiScr.sheet.focus, wifiPanel.cursor)
	}
	if !key(sdl.K_ESCAPE) || wifiScr.sheet.open || transitionPhase != "none" {
		t.Fatal("Escape in the sheet did more than close it")
	}

	// A on the connected network opens its details instead of rejoining it.
	wifiPanel.cursor = 0
	if !key(sdl.K_RETURN) || !wifiScr.sheet.open || wifiScr.sheetSSID != "HomeNet" || wifiPanel.busy {
		t.Fatalf("A on the connected network: sheet %v (%q), busy %v", wifiScr.sheet.open, wifiScr.sheetSSID, wifiPanel.busy)
	}
	key(sdl.K_ESCAPE)

	// I opens the diagnostics; Escape closes them and stays on the page.
	if !key(sdl.K_i) || !wifiPanel.diagOpen || wifiScr.sheetMode != wifiScrSheetDiag {
		t.Fatal("I did not open the diagnostics sheet")
	}
	if got := wifiScrPills(); got != "refresh,copy,close" {
		t.Fatalf("diagnostics pills = %s", got)
	}
	if !key(sdl.K_ESCAPE) || wifiPanel.diagOpen || wifiScr.sheet.open || transitionPhase != "none" {
		t.Fatal("Escape did not close only the diagnostics")
	}

	// An armed forget is cancelled by the first Escape, the page left by the
	// second.
	wifiPanel.confirmForget, wifiPanel.confirmAt = "Office", time.Now()
	if !key(sdl.K_ESCAPE) || wifiPanel.confirmForget != "" || transitionPhase != "none" {
		t.Fatal("the first Escape did not just disarm the forget")
	}
	if !key(sdl.K_ESCAPE) || pendingSceneIndex != 0 || transitionPhase != "fade-out" {
		t.Fatalf("the second Escape started phase %q to scene %d, want Home", transitionPhase, pendingSceneIndex)
	}

	// The password keyboard keeps its keys.
	prevVK := virtualKeyboardActive
	t.Cleanup(func() { virtualKeyboardActive = prevVK })
	virtualKeyboardActive = true
	if key(sdl.K_DOWN) {
		t.Fatal("the page took a key while the keyboard was open")
	}
}

// TestWiFiScrPadMirrorsTheKeys: the handheld's buttons reach every action the
// keyboard does, and B always backs out one level.
func TestWiFiScrPadMirrorsTheKeys(t *testing.T) {
	config := wifiScrTestPage(t)
	pad := func(button uint8) bool {
		return wifiScrPad(&sdl.ControllerButtonEvent{Type: sdl.CONTROLLERBUTTONDOWN, Button: button}, config)
	}
	if !pad(sdl.CONTROLLER_BUTTON_DPAD_DOWN) || wifiPanel.cursor != 1 {
		t.Fatalf("D-pad Down left the cursor on %d", wifiPanel.cursor)
	}
	if !pad(sdl.CONTROLLER_BUTTON_X) || !wifiScr.sheet.open || wifiScr.sheetSSID != "Office" {
		t.Fatal("X did not open the details")
	}
	if !pad(sdl.CONTROLLER_BUTTON_B) || wifiScr.sheet.open || transitionPhase != "none" {
		t.Fatal("B in the sheet did more than close it")
	}
	if !pad(sdl.CONTROLLER_BUTTON_BACK) || wifiScr.sheetMode != wifiScrSheetDiag || !wifiPanel.diagOpen {
		t.Fatal("Select did not open the diagnostics")
	}
	if !pad(sdl.CONTROLLER_BUTTON_B) || wifiPanel.diagOpen {
		t.Fatal("B did not close the diagnostics")
	}
	if !pad(sdl.CONTROLLER_BUTTON_RIGHTSHOULDER) || wifiPanel.cursor != 2 {
		t.Fatalf("R1 left the cursor on %d, want the last network", wifiPanel.cursor)
	}
	if !pad(sdl.CONTROLLER_BUTTON_LEFTSHOULDER) || wifiPanel.cursor != 0 {
		t.Fatalf("L1 left the cursor on %d, want the first network", wifiPanel.cursor)
	}
	if pad(sdl.CONTROLLER_BUTTON_GUIDE) {
		t.Fatal("an unbound button was taken")
	}
	if !pad(sdl.CONTROLLER_BUTTON_B) || pendingSceneIndex != 0 || transitionPhase != "fade-out" {
		t.Fatalf("B on the list started phase %q to scene %d, want Home", transitionPhase, pendingSceneIndex)
	}
}

