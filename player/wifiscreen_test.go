// wifiScrPinMeter makes the corner meter read level for the test.
func wifiScrPinMeter(t *testing.T, level int) {
	t.Helper()
	prev := statusWiFiSignal
	statusWiFiSignal = func() int { return level }
	t.Cleanup(func() { statusWiFiSignal = prev })
}

// wifiScrTestPage puts the page on screen with a known list — HomeNet
// connected (saved, secured), Office saved and in range, Cafe open — and
// nothing in flight. A details read counts as already running, so opening the
// connected network's details does not start a real one.
func wifiScrTestPage(t *testing.T) *Config {
	t.Helper()
	config := toolsHubTestNav(t)
	currentSceneIndex = sceneIndexExact(config, wifiScrSceneName)
	sceneHistory = []int{0}
	wifiScrPinMeter(t, 4)

	wifiScrDetails.mu.Lock()
	prevSample, prevBusy := wifiScrDetails.sample, wifiScrDetails.busy
	wifiScrDetails.busy = true
	wifiScrDetails.mu.Unlock()
	t.Cleanup(func() {
		wifiScrDetails.mu.Lock()
		wifiScrDetails.sample, wifiScrDetails.busy = prevSample, prevBusy
		wifiScrDetails.mu.Unlock()
	})

	wifiPanel = wifiPanelState{
		available: true,
		radioOn:   true,
		radioOK:   true,
		loadedAt:  time.Now(),
		status:    wifiStatus{State: wifiCompleteState, SSID: "HomeNet", IP: "192.168.1.20", Connected: true},
		networks: []wifiNetwork{
			{SSID: "HomeNet", BSSID: "aa:bb:cc:dd:ee:01", Signal: -47, Secured: true, Saved: true, Active: true},
			{SSID: "Office", BSSID: "aa:bb:cc:dd:ee:02", Signal: -66, Secured: true, Saved: true},
			{SSID: "Cafe", BSSID: "aa:bb:cc:dd:ee:03", Signal: -82},
		},
		// A fresh report: the diagnostics sheet opens without probing.
		diag: wifiDiagReport{At: time.Now(), Entries: []wifiDiagEntry{{Label: "Interface", Value: "wlan0", State: wifiDiagOK}}},
	}
	wifiScr.zone, wifiScr.ctrl = 0, 0
	wifiScr.sheet = toolsHubSheet{}
	wifiScr.sheetMode = wifiScrSheetNone
	wifiScr.fresh = false
	wifiScr.follow = true
	wifiScr.ctrls = nil
	wifiScrBuildCtrls()
	return config
}

// wifiScrPills lists the open sheet's actions.
func wifiScrPills() string {
	ids := make([]string, len(wifiScr.sheet.pills))
	for i, p := range wifiScr.sheet.pills {
		ids[i] = p.id
	}
	return strings.Join(ids, ",")
}

