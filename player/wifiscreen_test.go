// TestWiFiScrRendersThePage draws the page at the panel sizes the app runs on
// and checks its geometry and its touch targets: every row inside the list's
// viewport with its details button inside the row, the header controls on the
// title's line, the sheets' pills on their card, and taps that land where the
// pad would.
func TestWiFiScrRendersThePage(t *testing.T) {
	if testing.Short() {
		t.Skip("render probe skipped in -short mode")
	}
	config := wifiScrTestPage(t)
	renderer := probeRenderer(t)
	prevEngine := focusEngine
	focusEngine = NewFocusEngine()
	t.Cleanup(func() { focusEngine = prevEngine })

	frame := func() {
		renderer.SetDrawColor(9, 14, 25, 255)
		renderer.Clear()
		renderWiFiScr(renderer, config)
	}
	for _, size := range []struct{ w, h int32 }{{probeW, probeH}, {1024, 768}, {800, 480}} {
		withScreen(t, size.w, size.h)
		wifiScr.lastAt = 0
		wifiScr.follow = true
		frame()
		view := wifiScr.view
		if view.W <= 0 || view.H <= 0 || view.X < 0 || view.X+view.W > size.w || view.Y+view.H > size.h {
			t.Fatalf("%dx%d: list viewport %+v", size.w, size.h, view)
		}
		if len(wifiScr.rowRects) != len(wifiPanel.networks) {
			t.Fatalf("%dx%d: %d row targets for %d networks", size.w, size.h, len(wifiScr.rowRects), len(wifiPanel.networks))
		}
		if wifiScr.rowRects[0].W == 0 {
			t.Fatalf("%dx%d: the connected network is not on screen", size.w, size.h)
		}
		for i, r := range wifiScr.rowRects {
			if r.W == 0 {
				continue // scrolled out of a short screen
			}
			if r.X < view.X || r.X+r.W > view.X+view.W || r.Y < view.Y || r.Y+r.H > view.Y+view.H {
				t.Errorf("%dx%d: row %d %+v leaves the viewport %+v", size.w, size.h, i, r, view)
			}
			if info := wifiScr.infoRects[i]; info.W > 0 && (info.X < r.X || info.X+info.W > r.X+r.W) {
				t.Errorf("%dx%d: row %d's details button %+v leaves the row %+v", size.w, size.h, i, info, r)
			}
		}
		for _, c := range wifiScr.ctrls {
			if c.rect.W <= 0 || c.rect.H < 36 || c.rect.X+c.rect.W > size.w || c.rect.Y+c.rect.H > view.Y {
				t.Errorf("%dx%d: header control %q at %+v", size.w, size.h, c.id, c.rect)
			}
		}
	}

	withScreen(t, probeW, probeH)
	frame()
	// The details button opens that network's sheet; its pills are finger-sized
	// targets on the card, and Close closes it.
	info := wifiScr.infoRects[1]
	if !wifiScrClick(info.X+info.W/2, info.Y+info.H/2, config) || !wifiScr.sheet.open || wifiScr.sheetSSID != "Office" {
		t.Fatalf("tapping Office's details button opened %q (open %v)", wifiScr.sheetSSID, wifiScr.sheet.open)
	}
	frame()
	s := &wifiScr.sheet
	if len(s.pillRects) != len(s.pills) || len(s.pills) != 3 {
		t.Fatalf("sheet drew %d pill targets for %d pills", len(s.pillRects), len(s.pills))
	}
	for i, r := range s.pillRects {
		if r.H < 36 || !pointInRect(r.X, r.Y, s.card) || !pointInRect(r.X+r.W-1, r.Y+r.H-1, s.card) {
			t.Errorf("pill %d %+v is not a target on the card %+v", i, r, s.card)
		}
	}
	closeRect := s.pillRects[len(s.pillRects)-1]
	if !wifiScrClick(closeRect.X+closeRect.W/2, closeRect.Y+closeRect.H/2, config) || s.open {
		t.Fatal("tapping Close did not close the sheet")
	}

	// A tap on the connected row selects it and opens its details.
	frame()
	row := wifiScr.rowRects[0]
	if !wifiScrClick(row.X+24, row.Y+row.H/2, config) || wifiPanel.cursor != 0 || wifiScr.sheetSSID != "HomeNet" || !s.open {
		t.Fatalf("tapping the connected row: cursor %d, sheet %q (open %v)", wifiPanel.cursor, wifiScr.sheetSSID, s.open)
	}
	// A tap outside the card closes the sheet.
	frame()
	if !wifiScrClick(4, probeH-4, config) || s.open {
		t.Fatal("tapping outside the card left the sheet open")
	}

	// The header's Diagnostics control opens the diagnostics.
	frame()
	for _, c := range wifiScr.ctrls {
		if c.id == "diag" {
			if !wifiScrClick(c.rect.X+c.rect.W/2, c.rect.Y+c.rect.H/2, config) {
				t.Fatal("the Diagnostics control did not take the tap")
			}
		}
	}
	if !wifiPanel.diagOpen || wifiScr.sheetMode != wifiScrSheetDiag {
		t.Fatal("the Diagnostics control did not open the diagnostics")
	}
	frame()
	if len(s.lines) == 0 {
		t.Fatal("the diagnostics sheet laid out no rows")
	}
	wifiScrCloseSheet()

	// With no adapter the list explains itself and offers Diagnostics.
	wifiPanel = wifiPanelState{detail: "No wireless network interface on this device",
		diag: wifiDiagReport{At: time.Now(), Entries: []wifiDiagEntry{{Label: "Interface", Value: "none found", State: wifiDiagErr}}}}
	frame()
	if len(wifiScr.rowRects) != 0 || wifiScr.emptyRect.W == 0 || wifiScr.emptyAction != "diag" {
		t.Fatalf("no-adapter page: %d rows, empty button %+v (%q)", len(wifiScr.rowRects), wifiScr.emptyRect, wifiScr.emptyAction)
	}
	r := wifiScr.emptyRect
	if !wifiScrClick(r.X+r.W/2, r.Y+r.H/2, config) || wifiScr.sheetMode != wifiScrSheetDiag {
		t.Fatal("the empty state's button did not open the diagnostics")
	}
}
