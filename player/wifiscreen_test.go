func TestWiFiScrEmptyStatesOfferOneAction(t *testing.T) {
	cases := []struct {
		name          string
		panel         wifiPanelState
		title, action string
	}{
		{"no adapter", wifiPanelState{detail: "No wireless network interface on this device"}, "Wi-Fi is not available", "diag"},
		{"radio off, no supplicant yet", wifiPanelState{startable: true, radioOK: true}, "Wi-Fi is off", "radio"},
		{"radio off", wifiPanelState{available: true, radioOK: true}, "Wi-Fi is off", "radio"},
		{"supplicant down", wifiPanelState{startable: true, radioOn: true, radioOK: true}, "Wi-Fi is not running", "radio"},
		{"scanning", wifiPanelState{available: true, radioOn: true, busy: true, busyLabel: "Scanning for networks…"}, "", ""},
		{"scan refused", wifiPanelState{available: true, radioOn: true, scanErr: "the supplicant is busy"}, "Could not scan", "scan"},
		{"backend error", wifiPanelState{available: true, radioOn: true, err: "wpa_cli failed"}, "Wi-Fi did not answer", "scan"},
		{"nothing around", wifiPanelState{available: true, radioOn: true}, "No networks found", "scan"},
	}
	prev := wifiPanel
	t.Cleanup(func() { wifiPanel = prev })
	for _, c := range cases {
		wifiPanel = c.panel
		_, title, _, button, action := wifiScrEmptyState()
		if title != c.title || action != c.action {
			t.Errorf("%s: %q / %q, want %q / %q", c.name, title, action, c.title, c.action)
		}
		if (action == "") != (button == "") {
			t.Errorf("%s: button %q for action %q", c.name, button, action)
		}
	}
}

