package main

// psremote_ps4.go — PS4 LAN pairing, in Go.
//
// PS4 registration is a small, self-contained protocol: an 8-digit PIN is
// folded into an AES key, wrapped in a 480-byte request blob with an
// HMAC-derived IV, POSTed to the console, and the console answers with an
// encrypted block carrying the registration key and the 16-byte session key.
// There is no PSN round-trip and no native helper involved, so JukaHub can pair
// a PS4 by itself — the Python port used to do this, which is one of the two
// reasons the Vietnamese app had to be installed at all.
//
// The byte layout, the key tables and the CFB construction follow chiaki's
// registration code (and the port's Python version of it) exactly. The test
// file pins the result against payloads generated by that reference
// implementation, so a refactor here cannot silently change the wire format.

