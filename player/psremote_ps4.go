func mustHex(value string) []byte {
	raw, err := hex.DecodeString(strings.TrimSpace(value))
	if err != nil {
		panic("psremote: bad constant: " + err.Error())
	}
	return raw
}

// ps4ParsePin accepts the 8 digits the console shows on its Add Device screen.
func ps4ParsePin(pin string) (uint32, error) {
	text := strings.TrimSpace(pin)
	if len(text) != 8 {
		return 0, errors.New("the PIN is 8 digits")
	}
	for _, r := range text {
		if r < '0' || r > '9' {
			return 0, errors.New("the PIN is 8 digits")
		}
	}
	value, err := strconv.ParseUint(text, 10, 32)
	if err != nil {
		return 0, errors.New("the PIN is 8 digits")
	}
	return uint32(value), nil
}

// ps4DecodeAccountID turns the optional PSN Account-ID into its 8 raw bytes.
// An empty value means "offline default", which the console accepts when the
// account is not linked.
func ps4DecodeAccountID(value string) ([8]byte, bool, error) {
	var out [8]byte
	text := strings.TrimSpace(value)
	if text == "" || strings.HasPrefix(text, "stub-rp-key-") {
		return out, true, nil
	}
	raw, err := base64.StdEncoding.DecodeString(text)
	if err != nil {
		return out, false, errors.New("the PSN Account-ID is not valid base64")
	}
	if len(raw) != 8 {
		return out, false, fmt.Errorf("the PSN Account-ID must decode to 8 bytes, got %d", len(raw))
	}
	copy(out[:], raw)
	return out, false, nil
}

// ps4IV derives the CFB IV from the ambassador and the protocol key.
func ps4IV(ambassador []byte, pre10 bool) [16]byte {
	key := ps4HMACKey
	if pre10 {
		key = ps4HMACKeyOld
	}
	mac := hmac.New(sha256.New, key)
	mac.Write(ambassador)
	mac.Write(make([]byte, 8))
	var iv [16]byte
	copy(iv[:], mac.Sum(nil))
	return iv
}

// ps4CFB applies CFB-128 with the derived IV, in either direction.
func ps4CFB(data, key, ambassador []byte, decrypt, pre10 bool) ([]byte, error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	iv := ps4IV(ambassador, pre10)
	out := make([]byte, len(data))
	var stream cipher.Stream
	if decrypt {
		stream = cipher.NewCFBDecrypter(block, iv[:])
	} else {
		stream = cipher.NewCFBEncrypter(block, iv[:])
	}
	stream.XORKeyStream(out, data)
	return out, nil
}

// ps4BuildPayload builds the console request body and returns the AES key the
// response will be encrypted with.
func ps4BuildPayload(pin uint32, accountID [8]byte, ambassador []byte, pre10 bool) (payload, bright []byte, err error) {
	if len(ambassador) != 16 {
		return nil, nil, errors.New("the PS4 ambassador must be 16 bytes")
	}
	payload = bytes.Repeat([]byte{'A'}, ps4InnerOffset)
	pinBytes := make([]byte, 4)
	binary.BigEndian.PutUint32(pinBytes, pin)
	clientType := ps4ClientType

	if !pre10 {
		keyZeroOffset := int(payload[0x18D] & 0x1F)
		keyOneOffset := int(payload[0] >> 3)
		bright = make([]byte, 16)
		for i := 0; i < 16; i++ {
			bright[i] = ps4KeysZero[i*0x20+keyZeroOffset]
		}
		for i := 0; i < 4; i++ {
			bright[12+i] ^= pinBytes[i]
		}
		aeropause := make([]byte, 16)
		for i := 0; i < 16; i++ {
			aeropause[i] = byte((int(ambassador[i]^ps4KeysOne[i*0x20+keyOneOffset]) + 0x29 + i) & 0xFF)
		}
		copy(payload[0xC7:0xCF], aeropause[8:])
		copy(payload[0x191:0x199], aeropause[:8])
	} else {
		bright = append([]byte{}, ps4AESKeyOld...)
		for i := 0; i < 4; i++ {
			bright[i] ^= pinBytes[i]
		}
		aeropause := make([]byte, 16)
		for i := 0; i < 16; i++ {
			aeropause[i] = byte((int(ambassador[i])-i-0x29)&0xFF) ^ ps4EchoOld[i]
		}
		copy(payload[0x11C:0x12C], aeropause)
		clientType = ps4ClientTypeOld
	}

	inner := []byte("Client-Type: " + clientType + "\r\nNp-AccountId: " +
		base64.StdEncoding.EncodeToString(accountID[:]) + "\r\n")
	encrypted, err := ps4CFB(inner, bright, ambassador, false, pre10)
	if err != nil {
		return nil, nil, err
	}
	return append(payload, encrypted...), bright, nil
}

// ps4Search asks the console's registration port to identify itself; its reply
// tells us where to open the registration connection.
func ps4Search(host string, timeout time.Duration) (*net.UDPAddr, error) {
	port := ps4RegistPort
	if ps4SearchPortOverride > 0 {
		port = ps4SearchPortOverride
	}
	conn, err := net.ListenUDP("udp4", &net.UDPAddr{})
	if err != nil {
		return nil, err
	}
	defer conn.Close()
	target, err := net.ResolveUDPAddr("udp4", net.JoinHostPort(host, strconv.Itoa(port)))
	if err != nil {
		return nil, err
	}
	if _, err := conn.WriteToUDP([]byte("SRC2\x00"), target); err != nil {
		return nil, err
	}
	_ = conn.SetReadDeadline(time.Now().Add(timeout))
	buf := make([]byte, 256)
	n, from, err := conn.ReadFromUDP(buf)
	if err != nil {
		return nil, errors.New("the PS4 did not answer the registration search")
	}
	if n < 4 || string(buf[:4]) != "RES2" {
		return nil, errors.New("the PS4 sent an invalid registration reply")
	}
	return from, nil
}

// ps4HTTPResult is one parsed response: status code, headers and body.
type ps4HTTPResult struct {
	Status  int
	Reason  string
	Headers map[string]string
	Body    []byte
}

func ps4ParseHTTPBlock(raw []byte) (ps4HTTPResult, error) {
	idx := bytes.Index(raw, []byte("\r\n\r\n"))
	separator := 4
	if idx < 0 {
		if alt := bytes.Index(raw, []byte("\n\n")); alt >= 0 {
			idx, separator = alt, 2
		}
	}
	if idx < 0 {
		// The decrypted registration answer is headers only on some consoles:
		// treat the whole payload as the header block instead of failing.
		idx, separator = len(raw), 0
	}
	headerText := strings.ReplaceAll(string(raw[:idx]), "\r\n", "\n")
	lines := strings.Split(headerText, "\n")
	result := ps4HTTPResult{Headers: map[string]string{}}
	statusLine := strings.TrimSpace(lines[0])
	fields := strings.Fields(statusLine)
	if len(fields) >= 2 {
		if code, err := strconv.Atoi(fields[1]); err == nil {
			result.Status = code
		}
	}
	if len(fields) >= 3 {
		result.Reason = strings.Join(fields[2:], " ")
	}
	for _, line := range lines[1:] {
		colon := strings.IndexByte(line, ':')
		if colon <= 0 {
			continue
		}
		key := strings.ToLower(strings.TrimSpace(line[:colon]))
		if key == "" {
			continue
		}
		result.Headers[key] = strings.TrimSpace(line[colon+1:])
	}
	result.Body = raw[idx+separator:]
	return result, nil
}

// ps4ReadResponse reads until the console closes the connection (it is asked to
// with Connection: close) and parses the HTTP framing.
func ps4ReadResponse(conn net.Conn, timeout time.Duration) (ps4HTTPResult, error) {
	_ = conn.SetReadDeadline(time.Now().Add(timeout))
	var data bytes.Buffer
	_, err := io.Copy(&data, io.LimitReader(conn, 1<<20))
	if err != nil && !errors.Is(err, io.EOF) {
		if netErr, ok := err.(net.Error); !ok || !netErr.Timeout() {
			return ps4HTTPResult{}, err
		}
	}
	if data.Len() == 0 {
		return ps4HTTPResult{}, errors.New("the PS4 sent an empty registration reply")
	}
	return ps4ParseHTTPBlock(data.Bytes())
}

// ps4ParseResultBody reads the decrypted registration headers into a console.
func ps4ParseResultBody(raw []byte) (psConsole, error) {
	result, err := ps4ParseHTTPBlock(raw)
	if err != nil {
		return psConsole{}, err
	}
	if result.Status != 0 && result.Status != 200 {
		reason := result.Headers["rp-application-reason"]
		detail := "the PS4 refused registration (HTTP " + strconv.Itoa(result.Status) + ")"
		if reason != "" {
			detail += ", reason " + reason
		}
		if result.Status == 403 {
			detail += " — close Add Device on the console, open it again for a fresh PIN, and retry"
		}
		return psConsole{}, errors.New(detail)
	}
	required := []string{"ps4-registkey", "rp-key", "ps4-mac"}
	for _, key := range required {
		if strings.TrimSpace(result.Headers[key]) == "" {
			return psConsole{}, errors.New("the PS4 response is missing " + key)
		}
	}
	rawRegist, err := hex.DecodeString(result.Headers["ps4-registkey"])
	if err != nil {
		return psConsole{}, errors.New("the PS4 sent an unreadable registration key")
	}
	rawRP, err := hex.DecodeString(result.Headers["rp-key"])
	if err != nil || len(rawRP) != 16 {
		return psConsole{}, errors.New("the PS4 sent an unreadable session key")
	}
	mac, err := hex.DecodeString(result.Headers["ps4-mac"])
	if err != nil || len(mac) != 6 {
		return psConsole{}, errors.New("the PS4 sent an unreadable MAC address")
	}
	// The key is an ASCII hex string on the wire. A console that answers with
	// raw bytes instead is accepted by hex-encoding those bytes, which is what
	// the reference implementation does.
	trimmed := bytes.TrimRight(rawRegist, "\x00")
	registKey := ""
	if trimmed != nil && allHexBytes(trimmed) {
		registKey = string(trimmed)
	} else {
		registKey = hex.EncodeToString(trimmed)
	}
	if registKey == "" {
		return psConsole{}, errors.New("the PS4 sent an empty registration key")
	}
	if !psRegistKeyValid(registKey) {
		return psConsole{}, errors.New("the PS4 sent an invalid registration key")
	}
	rpKeyType := 0
	if value := strings.TrimSpace(result.Headers["rp-keytype"]); value != "" {
		if parsed, err := strconv.ParseInt(value, 0, 32); err == nil {
			rpKeyType = int(parsed)
		}
	}
	return psConsole{
		Name:      result.Headers["ps4-nickname"],
		RegistKey: strings.ToLower(registKey),
		RPKey:     base64.StdEncoding.EncodeToString(rawRP),
		RPKeyType: rpKeyType,
		ServerMAC: hex.EncodeToString(mac),
		Target:    psTargetPS4FW10,
		PairedAt:  time.Now(),
	}, nil
}

// ps4Register pairs with a PS4 on the LAN. The target selects the protocol
// generation: 900 is the pre-10 path (FW 9.00), everything else uses 10.0.
func ps4Register(host, pin, accountID string, target int, timeout time.Duration) (psConsole, error) {
	host = strings.TrimSpace(host)
	if host == "" {
		return psConsole{}, errors.New("no console address")
	}
	pinValue, err := ps4ParsePin(pin)
	if err != nil {
		return psConsole{}, err
	}
	account, _, err := ps4DecodeAccountID(accountID)
	if err != nil {
		return psConsole{}, err
	}
	if timeout <= 0 {
		timeout = 10 * time.Second
	}
	pre10 := target == psTargetPS4FW9
	ambassador := ps4AmbassadorOverride
	if len(ambassador) == 0 {
		ambassador = make([]byte, 16)
		if _, err := rand.Read(ambassador); err != nil {
			return psConsole{}, err
		}
	}
	payload, bright, err := ps4BuildPayload(pinValue, account, ambassador, pre10)
	if err != nil {
		return psConsole{}, err
	}

	address, err := ps4Search(host, minDuration(timeout, 3*time.Second))
	if err != nil {
		return psConsole{}, err
	}
	time.Sleep(100 * time.Millisecond)

	path := ps4RegistPath
	version := ps4RegistVersion
	if pre10 {
		path = ps4RegistPathOld
		version = ps4RegistVersionOld
	}
	conn, err := net.DialTimeout("tcp", address.String(), minDuration(timeout, 3*time.Second))
	if err != nil {
		return psConsole{}, fmt.Errorf("could not reach the PS4 at %s: %w", address.String(), err)
	}
	defer conn.Close()
	_ = conn.SetWriteDeadline(time.Now().Add(timeout))
	header := fmt.Sprintf("POST %s HTTP/1.1\r\nHOST: 10.0.2.15\r\nUser-Agent: remoteplay Windows\r\nConnection: close\r\nContent-Length: %d\r\nRP-Version: %s\r\n\r\n", path, len(payload), version)
	if _, err := conn.Write(append([]byte(header), payload...)); err != nil {
		return psConsole{}, fmt.Errorf("could not send the pairing request: %w", err)
	}

	response, err := ps4ReadResponse(conn, minDuration(timeout, 3*time.Second))
	if err != nil {
		return psConsole{}, err
	}
	if response.Status != 200 {
		detail := "the PS4 refused pairing (HTTP " + strconv.Itoa(response.Status) + ")"
		if reason := response.Headers["rp-application-reason"]; reason != "" {
			detail += ", reason " + reason
		}
		if response.Status == 403 {
			detail += " — close Add Device on the console, open it again for a fresh PIN, and retry"
		}
		return psConsole{}, errors.New(detail)
	}
	if len(response.Body) == 0 {
		return psConsole{}, errors.New("the PS4 sent an empty registration body")
	}
	plain, err := ps4CFB(response.Body, bright, ambassador, true, pre10)
	if err != nil {
		return psConsole{}, err
	}
	console, err := ps4ParseResultBody(plain)
	if err != nil {
		return psConsole{}, err
	}
	console.Host = host
	if pre10 {
		console.Target = psTargetPS4FW9
	}
	return console, nil
}

// allHexBytes reports whether every byte is an ASCII hex character.
func allHexBytes(value []byte) bool {
	if len(value) == 0 {
		return false
	}
	for _, b := range value {
		if !((b >= '0' && b <= '9') || (b >= 'a' && b <= 'f') || (b >= 'A' && b <= 'F')) {
			return false
		}
	}
	return true
}

func minDuration(a, b time.Duration) time.Duration {
	if a < b {
		return a
	}
	return b
}
