#!/usr/bin/env python3
"""Generate osd_font.h, the glyph atlas chiaki-stream's on-screen display draws.

    cd player/native && python3 gen-osd-font.py ../Inter-Regular.ttf osd_font.h

The atlas holds printable ASCII (32..126) rendered from JukaHub's own Inter
Regular at FONT_SIZE pixels. Every glyph keeps a transparent 1 px border so
bilinear scaling never pulls a neighbour in, alpha is quantised to 4 bits (16
levels are plenty for anti-aliased text) and the pixels are run-length encoded
into plain string chunks:

    'a'..'z'  1..26 transparent pixels
    '0'..'9'  1..10 fully opaque pixels
    'A'..'N'  one pixel of alpha 1..14 (of 15)

Each chunk stays under the 4095 characters ISO C promises a string literal, so
-Wpedantic stays quiet. The output depends only on the font file and Pillow's
FreeType rasteriser; rerun this after changing either and commit the header.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_SIZE = 34
FIRST, LAST = 32, 126
ATLAS_W = 512
PAD = 1
CHUNK = 3000


def render_glyphs(font):
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = font.getlength(ch)
        canvas = Image.new("L", (FONT_SIZE * 4, ascent + descent + 16), 0)
        draw = ImageDraw.Draw(canvas)
        pen_x, top = FONT_SIZE, 8
        draw.text((pen_x, top + ascent), ch, font=font, fill=255, anchor="ls")
        box = canvas.getbbox()
        glyph = {"code": code, "adv64": int(round(advance * 64)), "w": 0, "h": 0, "bx": 0, "by": 0, "bmp": None}
        if box is not None:
            x0, y0, x1, y1 = box
            glyph.update(w=x1 - x0, h=y1 - y0, bx=x0 - pen_x, by=y0 - top, bmp=canvas.crop(box))
        glyphs.append(glyph)
    return ascent, descent, glyphs


def pack(glyphs):
    x = y = shelf = 0
    for g in glyphs:
        g["ax"] = g["ay"] = 0
        if g["bmp"] is None:
            continue
        w, h = g["w"] + 2 * PAD, g["h"] + 2 * PAD
        if x + w > ATLAS_W:
            x, y, shelf = 0, y + shelf, 0
        g["ax"], g["ay"] = x + PAD, y + PAD
        x += w
        shelf = max(shelf, h)
    return y + shelf


def encode(levels):
    out = []
    i, n = 0, len(levels)
    while i < n:
        v = levels[i]
        if v == 0 or v == 15:
            limit = 26 if v == 0 else 10
            run = 1
            while i + run < n and levels[i + run] == v and run < limit:
                run += 1
            out.append(chr((ord("a") if v == 0 else ord("0")) + run - 1))
            i += run
        else:
            out.append(chr(ord("A") + v - 1))
            i += 1
    return "".join(out)


def main(argv):
    ttf = argv[1] if len(argv) > 1 else "../Inter-Regular.ttf"
    out_path = argv[2] if len(argv) > 2 else "osd_font.h"
    font = ImageFont.truetype(ttf, FONT_SIZE)
    ascent, descent, glyphs = render_glyphs(font)
    atlas_h = pack(glyphs)
    atlas = Image.new("L", (ATLAS_W, atlas_h), 0)
    for g in glyphs:
        if g["bmp"] is not None:
            atlas.paste(g["bmp"], (g["ax"], g["ay"]))
    data = atlas.tobytes()
    levels = [(p * 15 + 127) // 255 for p in data]
    rle = encode(levels)
    chunks = [rle[i:i + CHUNK] for i in range(0, len(rle), CHUNK)]

    lines = []
    lines.append("/* osd_font.h - GENERATED by gen-osd-font.py from Inter-Regular.ttf (SIL OFL 1.1). Do not edit. */")
    lines.append("/* Regenerate: cd player/native && python3 gen-osd-font.py ../Inter-Regular.ttf osd_font.h */")
    lines.append("#ifndef JUKAHUB_OSD_FONT_H")
    lines.append("#define JUKAHUB_OSD_FONT_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("#define OSD_FONT_PIXEL_SIZE %d" % FONT_SIZE)
    lines.append("#define OSD_FONT_ASCENT %d" % ascent)
    lines.append("#define OSD_FONT_DESCENT %d" % descent)
    lines.append("#define OSD_FONT_LINE_HEIGHT %d" % (ascent + descent))
    lines.append("#define OSD_FONT_FIRST %d" % FIRST)
    lines.append("#define OSD_FONT_COUNT %d" % (LAST - FIRST + 1))
    lines.append("#define OSD_FONT_ATLAS_W %d" % ATLAS_W)
    lines.append("#define OSD_FONT_ATLAS_H %d" % atlas_h)
    lines.append("#define OSD_FONT_RLE_CHUNKS %d" % len(chunks))
    lines.append("")
    lines.append("/* One glyph: atlas position and size, bearing from the pen position (x) and")
    lines.append("   from the top of the line (y), advance in 1/64 pixel. */")
    lines.append("typedef struct {")
    lines.append("    int16_t x, y, w, h, bearing_x, bearing_y;")
    lines.append("    int32_t advance64;")
    lines.append("} OsdGlyph;")
    lines.append("")
    lines.append("static const OsdGlyph osd_font_glyphs[OSD_FONT_COUNT] = {")
    for g in glyphs:
        ch = chr(g["code"])
        label = ch if ch not in "\\*/" else "0x%02x" % g["code"]
        lines.append("    {%d, %d, %d, %d, %d, %d, %d}, /* %s */" % (
            g["ax"], g["ay"], g["w"], g["h"], g["bx"], g["by"], g["adv64"], "space" if ch == " " else label))
    lines.append("};")
    lines.append("")
    lines.append("/* 4-bit alpha, run-length encoded (see gen-osd-font.py), row-major, %dx%d. */" % (ATLAS_W, atlas_h))
    lines.append("static const char *const osd_font_rle[OSD_FONT_RLE_CHUNKS] = {")
    for c in chunks:
        lines.append('    "%s",' % c)
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    # CRLF, like every C file in this folder on a Windows checkout (the repo
    # stores LF; Git converts): a regenerated header is byte-identical to the
    # committed one instead of a whole-file line-ending diff.
    with open(out_path, "w", newline="\r\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s: atlas %dx%d, %d RLE chars in %d chunks, line height %d" % (
        out_path, ATLAS_W, atlas_h, len(rle), len(chunks), ascent + descent))
    if len(argv) > 3:
        atlas.save(argv[3])


if __name__ == "__main__":
    main(sys.argv)
